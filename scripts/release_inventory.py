def staged_python(manifest, stage, findings, metadata_lookup, top_levels):
    files = {entry['path']: entry for entry in manifest['files']}
    components = {}
    for path, entry in sorted(files.items()):
        if not path.startswith(INTERNAL):
            continue
        rest = path[len(INTERNAL):].split('/')
        if len(rest) != 2 or not (rest[0].endswith('.dist-info') and rest[1] == 'METADATA'
                                  or rest[0].endswith('.egg-info') and rest[1] == 'PKG-INFO'):
            continue
        try:
            data = stage.read(path, MAX_TEXT)
        except (Missing, Unsafe):
            findings.append({'code': 'stage_file_unreadable', 'subject': path})
            continue
        if sha_bytes(data) != entry['sha256']:
            findings.append({'code': 'stage_file_differs', 'subject': path})
            continue
        meta = email.parser.BytesHeaderParser().parsebytes(data)
        name, version = (meta.get('Name') or '').strip(), (meta.get('Version') or '').strip()
        if not name:
            findings.append({'code': 'metadata_without_name', 'subject': path})
            continue
        licence, how = declared(meta)
        folder = INTERNAL + rest[0] + '/'
        bundled = sorted(p for p in files if p.startswith(folder) and NOTICE_WORD.match(p.rsplit('/', 1)[-1]))
        components[normalize(name)] = {
            'ecosystem': 'python', 'name': name, 'version': version or None, 'licence': licence,
            'licence_source': 'bundle_metadata:' + how if licence else None, 'presence': 'bundle_metadata',
            'evidence': [path], 'bundled_notice_files': bundled}
    # Staged top-level modules the build environment maps to distributions (compiled packages and data folders).
    mapping = top_levels() if top_levels else {}
    seen_tops = sorted({path[len(INTERNAL):].split('/')[0].split('.')[0] for path in files if path.startswith(INTERNAL)})
    for top in seen_tops:
        for dist in mapping.get(top, ()):
            key = normalize(dist)
            if key in components:
                components[key].setdefault('modules', []).append(top)
                continue
            meta = metadata_lookup(dist) if metadata_lookup else None
            licence, how = declared(meta)
            components[key] = {'ecosystem': 'python', 'name': dist,
                               'version': (meta.get('Version') or None) if meta is not None else None,
                               'licence': licence, 'licence_source': 'build_environment:' + how if licence else None,
                               'presence': 'files_in_bundle', 'evidence': [INTERNAL + top], 'modules': [top],
                               'bundled_notice_files': []}
    return components


def pinned_python(requirements, components, metadata_lookup):
    pins = []
    for line in requirements.decode('utf-8', 'replace').splitlines():
        match = REQUIREMENT.match(line)
        if match:
            pins.append((match.group(1), match.group(2)))
    for name, version in pins:
        key = normalize(name)
        if key in components:
            components[key]['pinned'] = version
            if components[key]['version'] is None:
                components[key]['version'] = version
            continue
        meta = metadata_lookup(name) if metadata_lookup else None
        licence, how = declared(meta)
        components[key] = {'ecosystem': 'python', 'name': name, 'version': version, 'pinned': version,
                           'licence': licence, 'licence_source': 'build_environment:' + how if licence else None,
                           'presence': 'not_evidenced_in_bundle', 'evidence': [], 'bundled_notice_files': []}
    return pins


def npm_packages(lock):
    try:
        doc = parse_json(lock, 'package_lock')
    except EvidenceError as error:
        raise Refused(error.code, 'package-lock.json') from None
    packages = doc.get('packages') if isinstance(doc, dict) else None
    if not isinstance(packages, dict):
        raise Refused('package_lock_unsupported', 'Needs lockfileVersion 2 or 3 with a packages map.')
    out = []
    for key, entry in sorted(packages.items()):
        if not key or not isinstance(entry, dict) or entry.get('dev') or entry.get('devOptional') or entry.get('link'):
            continue
        name = entry.get('name') or key.rsplit('node_modules/', 1)[-1]
        licence = entry.get('license')
        if isinstance(entry.get('licenses'), list):  # the legacy array form
            licence = ' OR '.join(item.get('type', '') for item in entry['licenses'] if isinstance(item, dict)) or None
        out.append({'ecosystem': 'npm', 'name': name, 'version': entry.get('version'),
                    'licence': licence if isinstance(licence, str) and licence.strip() else None,
                    'licence_source': 'package-lock.json' if isinstance(licence, str) and licence.strip() else None,
                    'presence': 'production_dependency', 'evidence': [key]})
    return out


def cargo_crates(lock, cargo_home):
    text = lock.decode('utf-8', 'replace')
    registries = sorted(glob.glob(os.path.join(glob.escape(str(cargo_home)), 'registry', 'src', '*', '')))
    out = []
    for block in re.split(r'(?m)^\[\[package\]\]\s*$', text)[1:]:
        fields = dict(re.findall(r'(?m)^(name|version|source)\s*=\s*"([^"]*)"\s*$', block))
        if 'name' not in fields or 'source' not in fields:
            continue  # the workspace's own crate
        licence, source = None, None
        for registry in registries:
            manifest = Path(registry) / f'{fields["name"]}-{fields.get("version", "")}' / 'Cargo.toml'
            try:
                data = read_explicit(manifest, 1_000_000, 'crate_manifest')
            except EvidenceError:
                continue
            licence = crate_licence(data)
            source = 'cargo_registry' if licence else None
            break
        out.append({'ecosystem': 'cargo', 'name': fields['name'], 'version': fields.get('version'), 'licence': licence,
                    'licence_source': source, 'presence': 'in_lockfile', 'evidence': [fields['source']]})
    return out, len(registries)


def crate_licence(data):
    text = data.decode('utf-8', 'replace')
    try:
        import tomllib
        package = tomllib.loads(text).get('package') or {}
        licence, path = package.get('license'), package.get('license-file')
    except (ImportError, ValueError):
        found = re.search(r'(?m)^license\s*=\s*"([^"]+)"', text)
        licence, path = (found.group(1) if found else None), None
    if isinstance(licence, str) and licence.strip():
        return licence.strip()
    if isinstance(path, str) and path.strip():
        return 'license-file: ' + path.strip()
    return None


