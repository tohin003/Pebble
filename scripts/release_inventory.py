"""Licence and SBOM inventory of a staged Pebble release (Phase 20, D20 section 1.4, track T5).

  release_inventory.py --stage-manifest C/stage/stage-manifest.json --report NEW [--stage-root DIR]
                       [--resources src-tauri/resources] [--requirements backend/requirements.txt]
                       [--package-lock package-lock.json] [--cargo-lock src-tauri/Cargo.lock]
                       [--cargo-home .runtime/toolchain/cargo] [--cargo-metadata M.json]

Every component the release ships, each with its declared licence and whether the notice folder
(src-tauri/resources/licenses/, or the resources root for the vendored AgentGuard and bloub notices) holds
its notice:

- python: every distribution whose metadata (*.dist-info/METADATA, *.egg-info/PKG-INFO) is in the staged
  backend/_internal, every distribution the build environment maps a staged top-level module to, and every
  pin in backend/requirements.txt, each with how the staged bundle evidences it;
- npm: every package in package-lock.json that can ship in dist/ (neither dev nor devOptional);
- cargo: every crate in src-tauri/Cargo.lock except the shell's own, with the licence from the local cargo
  registry sources when they exist; with --cargo-metadata (Phase 26), only the crates that
  `cargo metadata --filter-platform aarch64-apple-darwin` resolved, the same filter the notices file is generated
  with; the others are listed in the report's inputs as off-platform, never as components;
- native: llama.cpp b11499 (staged llama/), CPython and the PyInstaller bootloader in the frozen backend;
- vendored: AgentGuard and bloub.

The stage manifest is read with release_readiness.read_manifest; its paths are relative to the staged
resources folder (default: stage-manifest.json's sibling resources/), and every staged file read here must
hash to its manifest entry. A missing notice, an unknown licence, a staged notice that differs from the source
folder and a NOTICE.md reference to a missing licenses/ path are findings; a finding is never a pass, and the
result is "complete" only with none. Notice files are matched by name: <component>-LICENSE*, -COPYING*,
-NOTICE* or -AUTHORS* (names compared case-insensitively with -, _, ., @ and / folded), or a folder named
after the component. It never downloads anything, never writes into src-tauri/resources or the stage, and
creates the report exclusively.

Phase 24 (V1-046, V1-045, V1-047):
- licenses/THIRD-PARTY-NOTICES.txt, generated by the `notices` command below from the exact build inputs, is a
  notice source: a component listed there with its version and a licence text has its notice. A listed version that
  differs from the shipped one is a stale notice (notice_missing and notice_version_differs), and a notices file
  made from other lockfiles than the ones given is notices_inputs_differ.
- No GPL or LGPL library ships: a component whose every licence alternative is GPL, LGPL or AGPL (without the
  PyInstaller bootloader exception) is copyleft_licence, and a staged libx265, libde265 or libheif is
  copyleft_binary.
- Pebble's own Apache-2.0 LICENSE, OpenSSL and zstd (when staged) are components; bloub's notice is
  licenses/bloub-LICENSE.

  release_inventory.py notices --out src-tauri/resources/licenses/THIRD-PARTY-NOTICES.txt [--package-lock P]
                       [--node-modules node_modules] [--cargo-lock L] [--cargo-home H] [--cargo-metadata M.json]
                       [--lock backend/requirements.lock] [--python-license LICENSE.txt]

writes the notices file from: the production npm closure (licence files in node_modules), every crate of Cargo.lock
(or only those `cargo metadata --filter-platform aarch64-apple-darwin` lists) with the licence files in the local
registry sources, the runtime distributions of the hashed lock with the licence files of the interpreter that runs
it (run it with the build environment's python, so the versions are the shipped ones), CPython's LICENSE.txt (which
covers the OpenSSL and zstd it incorporates when it names them) and PyInstaller's COPYING.txt for the bootloader.
Identical texts are written once, with every component they apply to. It downloads nothing; a component without a
licence file is reported, and the command exits 10.

Exit codes: 0 complete, 10 gaps reported, 2 refused or usage, 1 crash.
"""

