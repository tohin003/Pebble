def stage_root_for(manifest_path, override):
    path = Path(override) if override else Path(os.path.abspath(manifest_path)).parent / 'resources'
    try:
        return Root(str(path), 'stage_root'), path
    except EvidenceError as error:
        raise Refused(error.code, str(path)) from None


def inventory(stage_manifest, *, stage_root=None, resources=ROOT / 'src-tauri/resources',
              requirements=ROOT / 'backend/requirements.txt', package_lock=ROOT / 'package-lock.json',
              cargo_lock=ROOT / 'src-tauri/Cargo.lock', cargo_home=ROOT / '.runtime/toolchain/cargo',
              metadata_lookup=environment_metadata, top_levels=environment_top_levels, now=None,
              requirements_lock=None, cargo_metadata=None):
    """requirements_lock: the hashed lock the notices file must have been generated from (checked when given).
    cargo_metadata: `cargo metadata --format-version 1 --filter-platform aarch64-apple-darwin` output; when given,
    only the crates it resolved are components (Phase 26: the notices file is generated with the same filter)."""
    data, manifest_record = explicit(stage_manifest, 'stage_manifest')
    manifest = read_stage_manifest(data)
    findings = []
    if bundle_digest(manifest['files']) != manifest['bundle_sha256']:
        findings.append({'code': 'stage_manifest_digest_mismatch', 'subject': None})
    staged = {entry['path']: entry['sha256'] for entry in manifest['files']}
    stage, stage_path = stage_root_for(stage_manifest, stage_root)
    with stage:
        python = staged_python(manifest, stage, findings, metadata_lookup, top_levels)
    req_data, req_record = explicit(requirements, 'requirements', MAX_TEXT)
    pins = pinned_python(req_data, python, metadata_lookup)
    lock_data, lock_record = explicit(package_lock, 'package_lock', MAX_JSON_BYTES)
    cargo_data, cargo_record = explicit(cargo_lock, 'cargo_lock', MAX_TEXT)
    npm = npm_packages(lock_data)
    crates, registries = cargo_crates(cargo_data, cargo_home)
    metadata_input = None
    if cargo_metadata is not None:
        metadata_data, metadata_record = explicit(cargo_metadata, 'cargo_metadata', 64_000_000)
        wanted = platform_crates(metadata_data)
        off_platform = sorted(f'{c["name"]}@{c["version"]}' for c in crates if (c['name'], c['version']) not in wanted)
        crates = [c for c in crates if (c['name'], c['version']) in wanted]
        metadata_input = {**metadata_record, 'platform_crates': len(crates), 'off_platform': off_platform}
    files, owners, top, notice_md, index = source_notices(resources)

    fixed = []
    for ecosystem, name, version, licence, evidence, notice_names, top_files in FIXED:
        present = [path for path in evidence if path in staged or any(p.startswith(path + '/') for p in staged)]
        fixed.append({'ecosystem': ecosystem, 'name': name, 'version': version, 'licence': licence,
                      'licence_source': 'NOTICE.md', 'presence': 'staged' if present else 'not_staged',
                      'evidence': present, '_notice': (notice_names, top_files)})
    for name, licence, pattern, _ in STAGED_NATIVE:
        present = sorted(path for path in staged if path.startswith(INTERNAL) and pattern.search(path))
        if present:
            fixed.append({'ecosystem': 'native', 'name': name, 'version': None, 'licence': licence,
                          'licence_source': 'NOTICE.md', 'presence': 'staged', 'evidence': present,
                          '_notice': ((name,), ())})
    components = list(python.values()) + npm + crates + fixed
    for item in components:
        names, top_files = item.pop('_notice', ((item['name'],), ()))
        item['notice'] = notice_for(owners, names, top_files, top, index, item['ecosystem'], item['version'],
                                    (item['name'],))
        subject = f'{item["ecosystem"]}:{item["name"]}@{item["version"]}'
        if item['notice']['status'] != 'present':
            findings.append({'code': 'notice_missing', 'subject': subject})
        if 'stale_versions' in item['notice']:
            findings.append({'code': 'notice_version_differs', 'subject': subject})
        if not item['licence']:
            findings.append({'code': 'licence_unknown', 'subject': subject})
        if blocks_distribution(item['licence']):
            findings.append({'code': 'copyleft_licence', 'subject': subject})
    components.sort(key=lambda item: (item['ecosystem'], normalize(item['name']), item['version'] or ''))
    for path in sorted(staged):
        if COPYLEFT_BINARY.search(path):
            findings.append({'code': 'copyleft_binary', 'subject': path})
    if index is not None:  # the notices file must come from these lockfiles
        digests = {'package-lock.json': lock_record['sha256'], 'Cargo.lock': cargo_record['sha256']}
        if requirements_lock is not None:
            digests['requirements.lock'] = explicit(requirements_lock, 'requirements_lock', MAX_TEXT)[1]['sha256']
        for label, digest in sorted(digests.items()):
            if index['inputs'].get(label) not in (None, digest):
                findings.append({'code': 'notices_inputs_differ', 'subject': label})

    # The staged notices must be the source folder's bytes; NOTICE.md must not name a missing licenses/ path.
    staged_licenses = {path[len('licenses/'):]: digest for path, digest in staged.items() if path.startswith('licenses/')}
    for rel in sorted(set(staged_licenses) | set(files)):
        if staged_licenses.get(rel) != files.get(rel):
            findings.append({'code': 'stage_licenses_differ', 'subject': 'licenses/' + rel})
    for name, digest in sorted(top.items()):
        if staged.get(name) != digest:
            findings.append({'code': 'stage_notice_differs', 'subject': name})
    for reference in sorted(set(NOTICE_REFERENCE.findall(notice_md or ''))):
        if not any(rel == reference or rel.startswith(reference + '/') for rel in files):
            findings.append({'code': 'notice_reference_missing', 'subject': 'licenses/' + reference})

    summary = {}
    for item in components:
        row = summary.setdefault(item['ecosystem'], {'components': 0, 'notice_present': 0, 'notice_missing': 0,
                                                     'licence_unknown': 0})
        row['components'] += 1
        row['notice_present' if item['notice']['status'] == 'present' else 'notice_missing'] += 1
        row['licence_unknown'] += not item['licence']
    counts = {}
    for finding in findings:
        counts[finding['code']] = counts.get(finding['code'], 0) + 1
    return {
        'format': FORMAT, 'created': (now or datetime.now(timezone.utc)).isoformat(),
        'inputs': {'stage_manifest': {**manifest_record, 'bundle_sha256': manifest['bundle_sha256'],
                                      'files': len(manifest['files'])},
                   'stage_root': str(stage_path), 'requirements': req_record, 'package_lock': lock_record,
                   'cargo_lock': cargo_record, 'cargo_metadata': metadata_input,
                   'cargo_registry': {'path': str(cargo_home), 'sources': registries},
                   'licenses': {'path': str(Path(resources) / 'licenses'), 'files': files},
                   'resource_notices': top, 'requirements_pins': len(pins),
                   'third_party_notices': None if index is None else {
                       'components': sum(len(v) for v in index['components'].values()), 'inputs': index['inputs']}},
        'components': components, 'summary': {'components': len(components), 'by_ecosystem': summary,
                                              'findings': counts},
        'findings': findings, 'result': 'complete' if not findings else 'gaps', 'limits': list(LIMITS)}


