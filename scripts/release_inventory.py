def read_text_file(path):
    with open(path, 'rb') as stream:
        return stream.read(MAX_TEXT).decode('utf-8', 'replace')


def licence_files(folder, extra=()):
    """[(name, text)] of the licence and notice files at the top of one package folder, in name order; extra names
    (a crate's license-file) count as well. Links are never followed."""
    try:
        names = sorted(os.listdir(folder))
    except OSError:
        return []
    found = []
    for name in names:
        path = Path(folder) / name
        if (NOTICE_WORD.match(name) or name in extra) and not path.is_symlink() and path.is_file():
            found.append((name, read_text_file(path)))
    return found


def environment_licences(name):
    """(version, [(file, text)]) of one distribution installed for the interpreter running this tool: the files in
    its dist-info licenses/ folder and the licence-like files at the dist-info top; (None, []) when absent."""
    try:
        dist = importlib.metadata.distribution(name)
    except importlib.metadata.PackageNotFoundError:
        return None, []
    found = []
    for item in dist.files or ():
        parts = item.parts
        if (len(parts) >= 2 and parts[0].endswith('.dist-info')
                and (parts[1] == 'licenses' and len(parts) > 2 or len(parts) == 2 and NOTICE_WORD.match(parts[1]))):
            path = Path(dist.locate_file(item))
            if path.is_file() and not path.is_symlink():
                found.append(('/'.join(parts[1:]), read_text_file(path)))
    return dist.version, sorted(found)


def cpython_licence():
    """(version, [(file, text)]) of the CPython that runs this tool: its LICENSE.txt, which also carries the licences
    of the libraries it incorporates."""
    import platform
    path = Path(sys.base_prefix) / 'lib' / ('python%d.%d' % sys.version_info[:2]) / 'LICENSE.txt'
    return platform.python_version(), ([('LICENSE.txt', read_text_file(path))] if path.is_file() else [])


def _clean(text):
    lines = [line.rstrip() for line in text.replace('\r\n', '\n').replace('\r', '\n').split('\n')]
    # A licence line equal to a separator would split the file when it is read back.
    lines = [line[:-1] if line in (NOTICES_RULE, NOTICES_SPLIT) else line for line in lines]
    return '\n'.join(lines).strip('\n') + '\n'


def _combined(files):
    if len(files) == 1:
        return _clean(files[0][1])
    return ''.join('==> %s <==\n%s\n' % (name, _clean(text)) for name, text in files)


def lock_runtime_pins(lock_text):
    """(name, version) of the runtime section of backend/requirements.lock, through scripts/package_backend.py."""
    spec = importlib.util.spec_from_file_location('release_inventory_packaging', ROOT / 'scripts' / 'package_backend.py')
    packaging = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(packaging)
    try:
        pins = packaging.read_lock(lock_text)
    except packaging.Refused as error:
        raise Refused('lock_unreadable', error.detail) from None
    return [(pin['name'], pin['version']) for pin in pins if pin['section'] == 'runtime']


def platform_crates(metadata):
    """{(name, version)} that `cargo metadata --filter-platform ...` resolved, or None."""
    if metadata is None:
        return None
    doc = parse_json(metadata, 'cargo_metadata')
    packages = doc.get('packages') if isinstance(doc, dict) else None
    if not isinstance(packages, list):
        raise Refused('cargo_metadata_unsupported', 'Use cargo metadata --format-version 1 output.')
    return {(item.get('name'), item.get('version')) for item in packages if isinstance(item, dict)}


def override_files(licenses):
    """{normalized owner: [(file, text)]} of the name-matched notice files in the resources licenses folder: the
    text for a package that ships none of its own (e.g. licenses/eastasianwidth-LICENSE)."""
    found = {}
    for name in sorted(os.listdir(licenses)) if licenses and os.path.isdir(licenses) else ():
        match = NOTICE_FILE.match(name)
        path = Path(licenses) / name
        if match and name != NOTICES and not path.is_symlink() and path.is_file():
            found.setdefault(normalize(match.group('owner')), []).append((name, read_text_file(path)))
    return found


def third_party_notices(*, package_lock, node_root, cargo_lock, cargo_home, requirements_lock, cargo_metadata=None,
                        python_licences=environment_licences, python_runtime=cpython_licence, licenses=None):
    """(text, report): the notices file for the exact inputs. A component that ships no licence file of its own uses
    a name-matched file in `licenses` (the resources licenses folder) when there is one; the others are reported in
    report['missing'] and left out of the text, so the inventory finds them."""
    entries, missing, overrides = [], [], override_files(licenses)

    def add(ecosystem, name, version, licence, files):
        files = files or overrides.get(normalize(name), [])
        if files:
            entries.append({'ecosystem': ecosystem, 'name': name, 'version': version, 'licence': licence or 'unknown',
                            'files': files})
        else:
            missing.append(f'{ecosystem}:{name}@{version}')

    lock_bytes = read_explicit(package_lock, MAX_JSON_BYTES, 'package_lock')
    for item in npm_packages(lock_bytes):
        add('npm', item['name'], item['version'], item['licence'], licence_files(Path(node_root) / item['evidence'][0]))
    cargo_bytes = read_explicit(cargo_lock, MAX_TEXT, 'cargo_lock')
    wanted = platform_crates(None if cargo_metadata is None else read_explicit(cargo_metadata, 64_000_000, 'cargo_metadata'))
    registries = sorted(glob.glob(os.path.join(glob.escape(str(cargo_home)), 'registry', 'src', '*', '')))
    for crate in cargo_crates(cargo_bytes, cargo_home)[0]:
        if wanted is not None and (crate['name'], crate['version']) not in wanted:
            continue
        folder = next((Path(r) / f'{crate["name"]}-{crate["version"]}' for r in registries
                       if (Path(r) / f'{crate["name"]}-{crate["version"]}').is_dir()), None)
        extra = ()
        if folder is not None and crate['licence'] and crate['licence'].startswith('license-file: '):
            extra = (Path(crate['licence'][len('license-file: '):]).name,)
        add('cargo', crate['name'], crate['version'], crate['licence'], licence_files(folder, extra) if folder else [])
    lock_text = read_explicit(requirements_lock, MAX_TEXT, 'requirements_lock')
    for name, version in lock_runtime_pins(lock_text.decode('utf-8', 'replace')):
        found, files = python_licences(name)
        if found is not None and found != version:
            missing.append(f'python:{name}@{version} (this interpreter has {found}; run with the build environment)')
            continue
        licence, _ = declared(environment_metadata(name))
        add('python', name, version, licence, files)
    version, files = python_runtime()
    add('native', 'CPython', version, 'PSF-2.0', files)
    for name, licence, _, mention in STAGED_NATIVE:  # incorporated by CPython: its LICENSE.txt carries their texts
        add('native', name, None, licence, files if files and mention.search(files[0][1]) else [])
    version, files = python_licences('pyinstaller')
    add('native', 'PyInstaller bootloader', version, 'GPL-2.0-or-later WITH Bootloader-exception',
        [item for item in files if re.match(r'(?i)(licenses/)?COPYING', item[0])] or files)

    groups = {}
    for entry in entries:
        text = _combined(entry['files'])
        groups.setdefault(text, []).append(entry)

    def order(entry):
        return (ECOSYSTEM_ORDER.index(entry['ecosystem']), normalize(entry['name']), entry['version'] or '')
    ordered = sorted(groups.items(), key=lambda item: min(order(entry) for entry in item[1]))
    head = [NOTICES_TITLE,
            'Generated by scripts/release_inventory.py notices from the inputs below. Do not edit it by hand; '
            'regenerate it after any dependency change.',
            'Each notice lists the components it applies to (ecosystem, name, version, declared licence, files), then '
            'the licence and notice text they ship with.',
            'Input: package-lock.json sha256 ' + sha_bytes(lock_bytes),
            'Input: Cargo.lock sha256 ' + sha_bytes(cargo_bytes),
            'Input: requirements.lock sha256 ' + sha_bytes(lock_text),
            'Components: %d; notices: %d' % (len(entries), len(ordered)), '']
    body = []
    for number, (text, group) in enumerate(ordered, 1):
        body += [NOTICES_RULE, 'Notice %d' % number]
        for entry in sorted(group, key=order):
            body.append('\t'.join(['', entry['ecosystem'], entry['name'], entry['version'] or '-', entry['licence'],
                                   ', '.join(name for name, _ in entry['files'])]))
        body += [NOTICES_SPLIT, text.rstrip('\n'), '']
    by_ecosystem = {}
    for entry in entries:
        by_ecosystem[entry['ecosystem']] = by_ecosystem.get(entry['ecosystem'], 0) + 1
    report = {'components': len(entries), 'notices': len(ordered), 'by_ecosystem': dict(sorted(by_ecosystem.items())),
              'missing': sorted(missing), 'cargo_registries': len(registries),
              'cargo_filtered_by_metadata': wanted is not None,
              'copyleft': sorted(f'{e["ecosystem"]}:{e["name"]}@{e["version"]}' for e in entries
                                 if blocks_distribution(e['licence']))}
    return '\n'.join(head + body), report


def write_notices(path, text):
    """Replace the notices file atomically; anything that is not an earlier generated notices file is refused."""
    path = Path(os.path.abspath(path))
    if os.path.lexists(path):
        if path.is_symlink() or not path.is_file() or not read_text_file(path).startswith(NOTICES_TITLE + '\n'):
            raise Refused('notices_target_refused', str(path))
    if not path.parent.is_dir():
        raise Refused('report_parent_missing', str(path.parent))
    temporary = path.with_name('.%s.%d.tmp' % (path.name, os.getpid()))
    fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, 'O_NOFOLLOW', 0), 0o644)
    with os.fdopen(fd, 'wb') as stream:
        stream.write(text.encode())
        stream.flush()
        os.fsync(stream.fileno())
    os.replace(temporary, path)


