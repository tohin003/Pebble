def write_new(path, report):
    data = (json.dumps(report, indent=2, sort_keys=True, ensure_ascii=False) + '\n').encode()
    try:
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, 'O_NOFOLLOW', 0), 0o600)
    except FileExistsError:
        raise Refused('report_exists', str(path)) from None
    try:
        view = memoryview(data)
        while view:
            view = view[os.write(fd, view):]
        os.fsync(fd)
    finally:
        os.close(fd)


def report_path(value, forbidden):
    path = Path(os.path.abspath(value))
    if os.path.lexists(path):
        raise Refused('report_exists', str(path))
    if not path.parent.is_dir():
        raise Refused('report_parent_missing', str(path.parent))
    real = os.path.realpath(path.parent)
    for root in forbidden:
        root = os.path.realpath(root)
        if real == root or real.startswith(root.rstrip('/') + '/'):
            raise Refused('report_inside_resources', 'Nothing is written into src-tauri/resources or the stage.')
    return path


