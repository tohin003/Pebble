class Refused(Exception):
    def __init__(self, code, detail=None):
        super().__init__(code if detail is None else f'{code}: {detail}')
        self.code, self.detail = code, detail


def normalize(name):
    return re.sub(r'[-_.@/]+', '-', name.casefold()).strip('-')


def sha_bytes(data):
    return hashlib.sha256(data).hexdigest()


def explicit(path, what, limit=MAX_JSON_BYTES):
    try:
        data = read_explicit(path, limit, what)
    except EvidenceError as error:
        raise Refused(error.code, f'{what}: {path}') from None
    return data, {'path': os.path.abspath(path), 'sha256': sha_bytes(data), 'bytes': len(data)}


def read_stage_manifest(data):
    """T1's C/stage/stage-manifest.json through release_readiness.read_manifest on its {path, bytes, sha256}
    entries and {path, target, kind} links; T1's extra per-entry keys (mode, source) are set aside."""
    try:
        doc = parse_json(data, 'stage_manifest')
    except EvidenceError as error:
        raise Refused(error.code, 'stage_manifest') from None
    files, links = (doc.get('files'), doc.get('links', [])) if isinstance(doc, dict) else (None, None)
    if (not isinstance(files, list) or not isinstance(links, list)
            or not all(isinstance(item, dict) for item in files + links)):
        raise Refused('schema', 'stage_manifest')
    core = {'files': [{key: item.get(key) for key in ('path', 'bytes', 'sha256')} for item in files],
            'links': [{key: item.get(key) for key in ('path', 'target', 'kind')} for item in links],
            'bundle_sha256': doc.get('bundle_sha256')}
    try:
        return read_manifest(json.dumps(core).encode())
    except EvidenceError as error:
        raise Refused(error.code, 'stage_manifest') from None


def environment_metadata(name):
    """The build environment's metadata for one distribution (read-only), else None."""
    try:
        return importlib.metadata.distribution(name).metadata
    except importlib.metadata.PackageNotFoundError:
        return None


def environment_top_levels():
    return importlib.metadata.packages_distributions()


def declared(meta):
    """(licence, how) from core metadata: License-Expression, licence classifiers, then a one-line License."""
    if meta is None:
        return None, None
    expression = (meta.get('License-Expression') or '').strip()
    if expression:
        return expression, 'License-Expression'
    classifiers = [item.split('::')[-1].strip() for item in (meta.get_all('Classifier') or [])
                   if item.startswith('License ::') and item.split('::')[-1].strip() != 'OSI Approved']
    if classifiers:
        return ' / '.join(dict.fromkeys(classifiers)), 'Classifier'
    text = (meta.get('License') or '').strip()
    if text and text.upper() != 'UNKNOWN':
        return (text, 'License') if '\n' not in text and len(text) <= 120 else ('licence text in metadata', 'License')
    return None, None


# ---- Notices -----------------------------------------------------------------------------------


def listing(root, parts):
    try:
        found = root.listing(parts)
    except Unsafe as error:
        raise Refused('resources_' + error.code, '/'.join(parts)) from None
    return found or []


def source_notices(resources):
    """The source notice folder: {relative path under licenses/: sha256}, an owner index and root notices."""
    try:
        root = Root(str(resources), 'resources')
    except EvidenceError as error:
        raise Refused(error.code, str(resources)) from None
    with root:
        files, owners = {}, {}
        for parts, info in listing(root, ('licenses',)):
            rel = '/'.join(parts[1:])
            if stat.S_ISDIR(info.st_mode):
                if len(parts) == 2:
                    owners.setdefault(normalize(parts[1]), [])
                continue
            if not stat.S_ISREG(info.st_mode):
                continue
            try:
                files[rel] = root.digest('/'.join(parts), MAX_TEXT)[0]
            except (Missing, Unsafe):
                continue
            if len(parts) > 2:
                owners.setdefault(normalize(parts[1]), []).append('licenses/' + rel)
            else:
                match = NOTICE_FILE.match(parts[1])
                if match:
                    owners.setdefault(normalize(match.group('owner')), []).append('licenses/' + rel)
        top = {}
        for name in ('NOTICE.md', 'AGENTGUARD-LICENSE', 'LICENSE'):
            try:
                top[name] = root.digest(name, MAX_TEXT)[0]
            except (Missing, Unsafe):
                pass
        try:
            notice_md = root.read('NOTICE.md', MAX_TEXT).decode('utf-8', 'replace')
        except (Missing, Unsafe):
            notice_md = None
        try:
            index = parse_notices(root.read('licenses/' + NOTICES, 64_000_000).decode('utf-8', 'replace'))
        except (Missing, Unsafe):
            index = None
    return files, owners, top, notice_md, index


def parse_notices(text):
    """The index of a generated notices file: {'inputs': {file: sha256}, 'components': {(ecosystem, normalized
    name): {version or None: [notice numbers]}}}. A notice counts only with a non-empty licence text; a file
    without the generated title is no index (None)."""
    if not text.startswith(NOTICES_TITLE + '\n'):
        return None
    inputs = dict(re.findall(r'(?m)^Input: (\S+) sha256 ([0-9a-f]{64})$', text.split('\n' + NOTICES_RULE + '\n')[0]))
    components = {}
    for section in text.split('\n' + NOTICES_RULE + '\n')[1:]:
        head, split, body = section.partition('\n' + NOTICES_SPLIT + '\n')
        number = re.match(r'Notice (\d+)\b', head)
        if not split or not number or not body.strip():
            continue
        for line in head.split('\n'):
            fields = line[1:].split('\t') if line.startswith('\t') else []
            if len(fields) >= 3 and fields[0] and fields[1]:
                version = None if fields[2] == '-' else fields[2]
                components.setdefault((fields[0], normalize(fields[1])), {}).setdefault(version, []).append(int(number.group(1)))
    return {'inputs': inputs, 'components': components}


def notice_for(owners, names, top_files=(), top=None, index=None, ecosystem=None, version=None, listed_as=()):
    """listed_as: further names the generated notices may list the component under (its own name)."""
    files = []
    for name in names:
        key = normalize(name)
        files += owners.get(key, [])
        for alias in ALIASES.get(key, ()):
            files += owners.get(alias, [])
    files += [name for name in top_files if top and name in top]
    files = sorted(dict.fromkeys(files))
    found = {'status': 'present' if files else 'missing', 'files': files}
    for name in (tuple(listed_as) + tuple(names)) if index else ():
        versions = index['components'].get((ecosystem, normalize(name)))
        if not versions:
            continue
        if version is None or version in versions:
            sections = sorted({n for v, numbers in versions.items() if version is None or v == version for n in numbers})
            return {'status': 'present', 'files': sorted(dict.fromkeys(files + ['licenses/' + NOTICES])), 'sections': sections}
        if not files:  # listed, but for another version: a stale notices file
            found['stale_versions'] = sorted(v for v in versions if v)
        break
    return found


def blocks_distribution(licence):
    """True when every alternative of a declared licence is GPL, LGPL or AGPL without a permitting exception."""
    if not licence:
        return False
    alternatives = [part for part in re.split(r'(?i)\s+OR\s+|\s+/\s+', licence.strip('() ')) if part.strip()]
    return bool(alternatives) and all(COPYLEFT.search(part) and not PERMITTED_EXCEPTION.search(part)
                                      for part in alternatives)


