#!/usr/bin/env python3
"""Parent tool: the local code-signing identity "Pebble Local Signing" (Phase 22, track k22-identity).

Subcommands: status, create and remove. What the person sees, rotation and removal:
docs/HARNESS_SIGNING_IDENTITY.md.

Safety model:
- Dry run by default. create and remove print, as JSON, every command they would run (secrets shown as
  placeholders) and every path they would write, and run nothing. --execute acts, and needs
  --i-am-the-parent-with-user-approval <stamp> (the UTC stamp of the person's approval, YYYYMMDDTHHMMSSZ).
- Apple's own tools only: /usr/bin/security and macOS's /usr/bin/openssl (LibreSSL). Nothing uses the network.
- The identity lives in its own keychain, ~/Library/Keychains/pebble-signing.keychain-db, whose random password is
  a mode-0600 file in ~/.pebble/signing/ (not ~/.pebble/runtime/, which the data-home layout lists as safe to
  delete: losing this password strands the identity). The login keychain's items are never read or changed, and
  the user keychain search list is put back exactly as it was after the new keychain is created.
- The private key is generated by openssl in a private temporary folder, encrypted with a one-time passphrase
  given on stdin, imported non-extractable (-x) with only codesign allowed to use it, and the folder is removed.
- Secrets never reach a report, a log or the environment. The keychain password is passed to `security` as an
  argument for the moment a command runs (macOS lets only the same user and root read another process's
  arguments, who can read the 0600 file anyway). Captured tool output is redacted before it is reported.
- create shows the person one macOS authorization prompt: the trust setting for code signing
  (security add-trusted-cert). remove shows one too (remove-trusted-cert).
- A stopped create or remove reports what it changed so far; remove undoes a partial create.

Exit codes: 0 done (or a clean dry run), 2 usage, 3 refused before any change, 4 stopped after a change.
"""
