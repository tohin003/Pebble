def status(paths, runner=run, probe=False):
    """What exists, read from files; with probe, also `security find-identity` on the identity's keychain."""
    report = {'paths': paths.report(), 'keychain': _mode(paths.keychain), 'folder': _mode(paths.folder),
              'password_file': _mode(paths.password), 'record': None, 'identity': None}
    try:
        record = read_record(paths)
    except Refused as error:
        report['record'] = {'refused': error.code}
        record = None
    if record:
        report['record'] = {key: record.get(key) for key in ('name', 'sha1', 'created_at', 'not_after',
                                                             'approved_stamp', 'keychain')}
        report['identity'] = {'name': record['name'], 'sha1': record['sha1'],
                              'designated_requirements': requirements(record['sha1'])}
    if probe and report['keychain'] and report['keychain']['kind'] == 'file':
        code, output = runner(find_argv(paths.keychain), None, COMMAND_SECONDS)
        report['probe'] = {'exit': code, 'valid_identities': [{'sha1': sha, 'name': name}
                                                              for sha, name in parse_identities(redact(output, []))]}
    report['state'] = ('created' if record and report['keychain'] and report['password_file'] else
                       'absent' if not any(report[key] for key in ('keychain', 'password_file', 'record')) else 'partial')
    return report


class Session:
    """One create or remove: its steps (shown with placeholders), what it changed, and its secrets."""

    def __init__(self, paths, runner, execute, temporary=None):
        self.paths, self.runner, self.execute = paths, runner, execute
        self.temporary = Path(temporary) if temporary else None
        self.steps, self.changed, self.hidden, self.values = [], [], [], {}
        self.work = None

    def secret(self, placeholder, value):
        self.values[placeholder] = value
        self.hidden.append(value)

    def resolve(self, argv):
        return [self.values.get(arg, arg) for arg in argv]

    def command(self, step, argv, *, stdin=None, writes=(), prompt=None, timeout=COMMAND_SECONDS, changes=True,
                accept=None):
        """Show or run one command. stdin is a list of placeholder lines. accept(code, text) may allow a
        non-zero exit (for example "already absent"). Returns the redacted output."""
        entry = {'step': step, 'argv': [str(arg) for arg in argv]}
        if stdin:
            entry['stdin'] = list(stdin)
        if writes:
            entry['writes'] = [str(path) for path in writes]
        if prompt:
            entry['prompt'] = prompt
        self.steps.append(entry)
        if not self.execute:
            return ''
        data = ('\n'.join(self.values.get(line, line) for line in stdin) + '\n').encode() if stdin else None
        code, output = self.runner(self.resolve([str(arg) for arg in argv]), data, timeout)
        text = redact(output, self.hidden)
        entry['exit'] = code
        if code != 0 and not (accept and code is not None and accept(code, text)):
            raise Refused('command_failed', 'A command failed: ' + step, step=step, exit=code, output=text)
        if changes:
            self.changed.append(step)
        return text

    def local(self, step, what, action=None, writes=()):
        entry = {'step': step, 'local': what}
        if writes:
            entry['writes'] = [str(path) for path in writes]
        self.steps.append(entry)
        if self.execute and action is not None:
            result = action()
            self.changed.append(step)
            return result
        return None

    def make_work(self):
        if self.execute:
            self.work = Path(tempfile.mkdtemp(prefix='pebble-signing-', dir=self.temporary))
            os.chmod(self.work, 0o700)
        return self.work or Path(self.temporary or tempfile.gettempdir()) / 'pebble-signing-XXXXXXXX'

    def clean_work(self):
        """Remove this session's own private temporary folder (it held encrypted key material)."""
        if self.work is not None and self.work.is_dir() and not self.work.is_symlink():
            shutil.rmtree(self.work, ignore_errors=True)
        self.work = None


def _create_preconditions(paths):
    problems = []
    if sys.platform != 'darwin':
        problems.append(('unsupported_platform', sys.platform))
    for tool in (SECURITY, OPENSSL):
        if not os.access(tool, os.X_OK):
            problems.append(('tool_missing', tool))
    for path in (paths.keychain, paths.password, paths.record):
        if os.path.lexists(path):
            problems.append(('already_exists', str(path)))
    folder = _mode(paths.folder)
    if folder and (folder['kind'] != 'directory' or any(os.scandir(paths.folder))):
        problems.append(('folder_not_empty', str(paths.folder)))
    if not paths.keychain.parent.is_dir():
        problems.append(('keychains_folder_missing', str(paths.keychain.parent)))
    return problems


def create(paths, runner=run, execute=False, approval=None, temporary=None, keep_in_search_list=False):
    """Create the identity, or (dry run) show exactly how. Returns (exit code, report)."""
    session = Session(paths, runner, execute, temporary)
    report = {'format': REPORT_FORMAT, 'action': 'create', 'mode': 'execute' if execute else 'dry-run',
              'paths': paths.report(), 'prompts': [PROMPT], 'steps': session.steps}
    problems = _create_preconditions(paths)
    if problems:
        report['refused'] = [{'code': code, 'detail': detail} for code, detail in problems]
        return EXIT_REFUSED, report
    password, transit = secrets.token_hex(32), secrets.token_hex(24)
    session.secret('<keychain-password>', password)
    session.secret('<transit-passphrase>', transit)
    serial = '0x%016x' % (secrets.randbits(63) | 1)
    kc = str(paths.keychain)
    try:
        listed = session.command('read-search-list', [SECURITY, 'list-keychains', '-d', 'user'], changes=False)
        original = parse_search_list(listed) if execute else None
        if execute and not any(path.endswith(('/login.keychain-db', '/login.keychain')) for path in original):
            raise Refused('search_list_unexpected', 'The user search list has no login keychain; nothing was changed.')
        session.local('make-folder', 'create %s (0700)' % paths.folder, lambda: _make_private_folder(paths),
                      [paths.folder])
        session.local('write-password', 'a random 256-bit keychain password, mode 0600',
                      lambda: _write_private(paths.password, password.encode()), [paths.password])
        work = session.make_work()
        config, key, cert, p12 = (work / name for name in ('openssl.cnf', 'key.pem', 'cert.pem', 'identity.p12'))
        session.local('write-openssl-config', 'the certificate profile: CN=%s, code signing only' % NAME,
                      lambda: _write_private(config, OPENSSL_CONFIG.encode()), [config])
        session.command('generate-key-and-certificate',
                        [OPENSSL, 'req', '-x509', '-newkey', KEY, '-sha256', '-days', str(DAYS), '-set_serial', serial,
                         '-config', config, '-extensions', 'pebble_codesign', '-keyout', key, '-passout', 'stdin',
                         '-out', cert], stdin=['<transit-passphrase>'], writes=[key, cert], changes=False)
        dates = session.command('inspect-certificate', [OPENSSL, 'x509', '-in', cert, '-noout', '-enddate'],
                                changes=False)
        match = re.search(r'notAfter=(.+)', dates)
        not_after = match.group(1).strip() if match else None
        session.command('package-identity',
                        [OPENSSL, 'pkcs12', '-export', '-inkey', key, '-in', cert, '-name', NAME, '-keypbe',
                         'PBE-SHA1-3DES', '-certpbe', 'PBE-SHA1-3DES', '-macalg', 'sha1', '-passin', 'stdin',
                         '-passout', 'stdin', '-out', p12], stdin=['<transit-passphrase>', '<transit-passphrase>'],
                        writes=[p12], changes=False)
        sha1 = certificate_sha1(cert.read_bytes()) if execute else None
        session.command('create-keychain', [SECURITY, 'create-keychain', '-p', '<keychain-password>', kc],
                        writes=[paths.keychain])
        if not keep_in_search_list:
            session.command('restore-search-list', [SECURITY, 'list-keychains', '-d', 'user', '-s',
                                                    *(original or ['<the list read above>'])])
            after = session.command('check-search-list', [SECURITY, 'list-keychains', '-d', 'user'], changes=False)
            if execute and parse_search_list(after) != original:
                raise Refused('search_list_not_restored', 'The user keychain search list differs from before.',
                              original=original, now=parse_search_list(after))
        session.command('keychain-settings', [SECURITY, 'set-keychain-settings', '-l', '-u', '-t', str(LOCK_SECONDS), kc])
        session.command('unlock-keychain', [SECURITY, 'unlock-keychain', '-p', '<keychain-password>', kc])
        session.command('import-identity', [SECURITY, 'import', p12, '-k', kc, '-f', 'pkcs12', '-P',
                                            '<transit-passphrase>', '-x', '-T', CODESIGN])
        session.command('allow-codesign', [SECURITY, 'set-key-partition-list', '-S', 'apple-tool:,apple:', '-s', '-k',
                                           '<keychain-password>', kc])
        session.command('trust-for-code-signing', [SECURITY, 'add-trusted-cert', '-r', 'trustRoot', '-p', 'codeSign',
                                                   '-k', kc, cert], prompt=PROMPT, timeout=PROMPT_SECONDS)
        found = session.command('verify-identity', find_argv(paths.keychain), changes=False)
        if execute:
            valid = parse_identities(found)  # a listing may repeat an identity (matching, then valid only)
            if set(valid) != {(sha1, NAME)}:
                raise Refused('identity_not_valid', 'The keychain does not hold exactly one valid Pebble identity.',
                              expected=sha1, found=[{'sha1': sha, 'name': name} for sha, name in valid])
        session.command('lock-keychain', [SECURITY, 'lock-keychain', kc])
        record = {'format': RECORD_FORMAT, 'name': NAME, 'sha1': sha1, 'keychain': kc, 'created_at': now(),
                  'not_after': not_after, 'valid_days': DAYS, 'key': KEY, 'approved_stamp': approval,
                  'search_list_restored': not keep_in_search_list,
                  'designated_requirements': requirements(sha1) if sha1 else None}
        session.local('write-record', 'the identity record (no secrets), mode 0600',
                      lambda: _write_private(paths.record, (json.dumps(record, indent=2) + '\n').encode()), [paths.record])
    except Refused as error:
        report.update(stopped=error.code, message=error.message, facts=error.facts, changed=list(session.changed),
                      recovery='Run `scripts/pebble_signing.py remove` (dry run first) to undo a partial create.')
        return (EXIT_STOPPED if session.changed else EXIT_REFUSED), report
    finally:
        session.clean_work()
    report['changed'] = list(session.changed)
    if execute:
        report['identity'] = {'name': NAME, 'sha1': sha1, 'designated_requirements': requirements(sha1)}
    else:
        report['identity'] = {'name': NAME, 'sha1': '<the new certificate SHA-1>',
                              'designated_requirements': requirements('<sha1>')}
    return EXIT_OK, report


def remove(paths, runner=run, execute=False, approval=None, temporary=None):
    """The reverse of create: the trust setting, the keychain, the password file and the record. Returns
    (exit code, report)."""
    session = Session(paths, runner, execute, temporary)
    report = {'format': REPORT_FORMAT, 'action': 'remove', 'mode': 'execute' if execute else 'dry-run',
              'paths': paths.report(), 'approved_stamp': approval, 'steps': session.steps,
              'prompts': ['macOS shows one authorization prompt to remove the code-signing trust setting.']}
    if sys.platform != 'darwin':
        report['refused'] = [{'code': 'unsupported_platform', 'detail': sys.platform}]
        return EXIT_REFUSED, report
    try:
        record = read_record(paths)
    except Refused as error:
        report['refused'] = [{'code': error.code, 'detail': str(paths.record)}]
        return EXIT_REFUSED, report
    present = {name: os.path.lexists(path) for name, path in (('keychain', paths.keychain),
                                                               ('password', paths.password), ('record', paths.record))}
    report['present'] = present
    if not any(present.values()):
        report['result'] = 'absent'
        return EXIT_OK, report
    kc = str(paths.keychain)
    try:
        if present['keychain']:
            work = session.make_work()
            cert = work / 'cert.pem'
            pem = session.command('export-certificate', [SECURITY, 'find-certificate', '-c', NAME, '-p', kc],
                                  changes=False)
            if execute:
                sha1 = certificate_sha1(pem)
                if record and sha1 != record['sha1']:
                    raise Refused('certificate_differs', 'The keychain holds another certificate than the record.',
                                  record=record['sha1'], keychain=sha1)
                _write_private(cert, pem.encode())
            session.command('remove-trust', [SECURITY, 'remove-trusted-cert', cert],
                            prompt=report['prompts'][0], timeout=PROMPT_SECONDS,
                            accept=lambda code, text: 'could not be found' in text)
            session.command('delete-keychain', [SECURITY, 'delete-keychain', kc])
        for name, path in (('password', paths.password), ('record', paths.record)):
            if present[name]:
                session.local('delete-' + name, 'remove %s' % path, lambda path=path: os.unlink(path))
        session.local('remove-folder-if-empty', 'remove %s when it is empty' % paths.folder,
                      lambda: paths.folder.is_dir() and not any(os.scandir(paths.folder)) and paths.folder.rmdir())
    except Refused as error:
        report.update(stopped=error.code, message=error.message, facts=error.facts, changed=list(session.changed))
        return (EXIT_STOPPED if session.changed else EXIT_REFUSED), report
    finally:
        session.clean_work()
    report['changed'] = list(session.changed)
    report['result'] = 'removed' if execute else 'planned'
    return EXIT_OK, report


def _stamp(value):
    if not STAMP.fullmatch(value):
        raise argparse.ArgumentTypeError('a UTC stamp such as 20261014T093000Z')
    return value


def main(argv=None, runner=None, home=None, temporary=None):
    """runner(argv, stdin bytes or None, timeout) -> (exit code or None, output bytes); tests inject one."""
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    sub = parser.add_subparsers(dest='action', required=True)
    shown = sub.add_parser('status', help='What exists (files only; --probe also asks security find-identity).')
    shown.add_argument('--probe', action='store_true')
    for name, text in (('create', 'Create the identity (dry run unless --execute).'),
                       ('remove', 'Remove the identity (dry run unless --execute).')):
        action = sub.add_parser(name, help=text)
        action.add_argument('--execute', action='store_true')
        action.add_argument('--i-am-the-parent-with-user-approval', dest='approval', metavar='STAMP', type=_stamp)
        if name == 'create':
            action.add_argument('--keep-in-search-list', action='store_true',
                                help='Leave the new keychain on the user search list (only if codesign cannot find '
                                     'the identity through --keychain).')
    args = parser.parse_args(argv)
    paths = Paths.at(home if home is not None else Path.home())
    if runner is None:
        def runner(command, stdin, timeout):
            return run(command, stdin, timeout, home=paths.home)
    if args.action == 'status':
        code, report = EXIT_OK, status(paths, runner, args.probe)
    elif args.execute and not args.approval:
        code, report = EXIT_USAGE, {'refused': [{'code': 'approval_required',
                                                 'detail': '--execute needs --i-am-the-parent-with-user-approval STAMP'}]}
    elif args.action == 'create':
        code, report = create(paths, runner, args.execute, args.approval, temporary, args.keep_in_search_list)
    else:
        code, report = remove(paths, runner, args.execute, args.approval, temporary)
    print(json.dumps(report, indent=2, default=str))
    return code


if __name__ == '__main__':
    sys.exit(main())
