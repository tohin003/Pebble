@dataclass(frozen=True)
class Identity:
    """A created local identity, from its record and files alone (nothing is run to find it)."""
    sha1: str
    name: str
    keychain: Path
    paths: Paths

    def requirement(self, identifier):
        return requirement(identifier, self.sha1)

    def describe(self):
        return {'name': self.name, 'sha1': self.sha1, 'keychain': str(self.keychain)}


def load_identity(home=None, sha1=None):
    """The local identity when its record, keychain and password file exist (and its SHA-1 is sha1, if given);
    else None. Reads three paths and runs nothing, so a plan can show it; a build checks it with find_argv()."""
    paths = Paths.at(home if home is not None else Path.home())
    record = read_record(paths)
    if record is None or not paths.keychain.is_file() or _mode(paths.password) is None:
        return None
    if sha1 is not None and record['sha1'] != sha1.upper():
        return None
    return Identity(record['sha1'], record['name'], paths.keychain, paths)


def find_argv(keychain):
    """The read-only check a build runs before signing: the identity is in its keychain and valid for code signing."""
    return [SECURITY, 'find-identity', '-v', '-p', 'codesigning', str(keychain)]


def sign_argv(identity, path, identifier, *, runtime=False, entitlements=None, preserve=False):
    """codesign argv that signs path with the identity, a stable identifier and the explicit designated requirement.
    No secret is in it. preserve keeps the existing signature's entitlements, flags and runtime version (the shell
    as Tauri signed it); runtime adds the hardened runtime with entitlements."""
    argv = [CODESIGN, '--force', '--sign', identity.sha1, '--keychain', str(identity.keychain),
            '--identifier', identifier, '--requirements', '=designated => ' + identity.requirement(identifier),
            '--timestamp=none']
    if preserve:
        argv.append('--preserve-metadata=entitlements,flags,runtime')
    if runtime:
        argv += ['--options', 'runtime']
    if entitlements is not None:
        argv += ['--entitlements', str(entitlements)]
    return argv + [str(path)]


def unlock(identity, runner=run):
    """Unlock the identity's keychain so codesign can use the key without a prompt; lock() it again right after
    signing. The password goes to `security` only; nothing it prints is reported unredacted."""
    password = _read_private(identity.paths.password).decode('ascii').strip()
    if not re.fullmatch(r'[0-9a-f]{64}', password):
        raise Refused('password_file_malformed', 'The keychain password file is malformed.',
                      path=str(identity.paths.password))
    code, output = runner([SECURITY, 'unlock-keychain', '-p', password, str(identity.keychain)], None, COMMAND_SECONDS)
    if code != 0:
        raise Refused('keychain_unlock_failed', 'The signing keychain could not be unlocked.', exit=code,
                      output=redact(output, [password]))


def lock(identity, runner=run):
    """Lock the identity's keychain. While it is unlocked, any process of this user could have codesign sign with the
    key, and code signed as Pebble inherits Pebble's privacy grants; so it stays locked except while a build signs."""
    code, output = runner([SECURITY, 'lock-keychain', str(identity.keychain)], None, COMMAND_SECONDS)
    if code != 0:
        raise Refused('keychain_lock_failed', 'The signing keychain could not be locked.', exit=code,
                      output=redact(output, []))


def check_pinned_helper(root, identity=None):
    """The pinned vault helper in <root>/src-tauri/resources/helpers, checked against its manifest and source:
    exactly the binary and its manifest (regular files), the binary's SHA-256, the source's SHA-256 and, given an
    identity, the same signer. Returns the manifest, or None when there is no helper folder. Reads files only; the
    candidate builder also checks the cdhash with codesign --display."""
    folder = Path(root) / 'src-tauri/resources' / HELPER_FOLDER
    if not os.path.lexists(folder):
        return None
    if _mode(folder)['kind'] != 'directory' or sorted(os.listdir(folder)) != sorted([HELPER_BINARY, HELPER_MANIFEST]):
        raise Refused('vault_helper_invalid', 'The helpers folder must hold exactly the helper and its manifest.',
                      path=str(folder), found=sorted(os.listdir(folder)) if folder.is_dir() else None)
    for name in (HELPER_BINARY, HELPER_MANIFEST):
        if _mode(folder / name)['kind'] != 'file':
            raise Refused('vault_helper_invalid', 'A pinned helper file is not a regular file.', path=str(folder / name))
    try:
        manifest = json.loads((folder / HELPER_MANIFEST).read_bytes())
    except ValueError:
        raise Refused('vault_helper_invalid', 'The helper manifest is not JSON.', path=str(folder / HELPER_MANIFEST)) from None
    keys = ('format', 'identifier', 'sha256', 'cdhash', 'designated_requirement', 'identity', 'source')
    if not isinstance(manifest, dict) or any(key not in manifest for key in keys) or manifest['format'] != HELPER_FORMAT:
        raise Refused('vault_helper_invalid', 'The helper manifest is malformed.', path=str(folder / HELPER_MANIFEST))
    binary = hashlib.sha256((folder / HELPER_BINARY).read_bytes()).hexdigest()
    if binary != manifest['sha256']:
        raise Refused('vault_helper_differs', 'The pinned helper is not the manifest\'s.', expected=manifest['sha256'],
                      actual=binary)
    try:
        source = hashlib.sha256((Path(root) / HELPER_SOURCE).read_bytes()).hexdigest()
    except OSError:
        source = None
    if not isinstance(manifest['source'], dict) or manifest['source'].get('sha256') != source:
        raise Refused('vault_helper_source_differs', 'The pinned helper was built from another source.',
                      expected=(manifest['source'] or {}).get('sha256') if isinstance(manifest['source'], dict) else None,
                      actual=source)
    if identity is not None and (manifest['identity'] or {}).get('sha1') != identity.sha1:
        raise Refused('vault_helper_identity_mismatch', 'The pinned helper is signed by another identity, so it would '
                      'refuse this build\'s backend.', helper=(manifest['identity'] or {}).get('sha1'),
                      build=identity.sha1)
    return manifest


def parse_codesign_blocks(text):
    """{executable: {identifier, cdhash, authorities, team, flags, designated}} from `codesign --display
    --verbose=4` and `codesign --display --requirements -` output for one or more paths."""
    blocks, current = {}, None
    for line in text.splitlines():
        key, separator, value = line.partition('=')
        if line.startswith('designated => ') and current is not None:
            current['designated'] = line[len('designated => '):].strip()
            continue
        if not separator:
            continue
        key, value = key.strip(), value.strip()
        if key == 'Executable':
            current = blocks.setdefault(value, {'identifier': None, 'cdhash': None, 'authorities': [], 'team': None,
                                                'flags': [], 'designated': None})
        elif current is None:
            continue
        elif key == 'Identifier':
            current['identifier'] = value
        elif key == 'CDHash':
            current['cdhash'] = value.lower()
        elif key == 'Authority':
            current['authorities'].append(value)
        elif key == 'TeamIdentifier':
            current['team'] = value
        elif key == 'CodeDirectory v':
            match = re.search(r'flags=0x[0-9a-fA-F]+\(([^)]*)\)', value)
            if match:
                current['flags'] = sorted(flag.strip() for flag in match.group(1).split(',') if flag.strip())
    return blocks


def same_requirement(text, expected):
    """codesign prints a requirement normalised (lower-case hashes, single spaces)."""
    def norm(value):
        return ' '.join((value or '').split()).lower()
    return norm(text) == norm(expected)


