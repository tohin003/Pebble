class Refused(Exception):
    """A refusal or a stop: a stable code, a message without secrets, and facts."""

    def __init__(self, code, message, **facts):
        super().__init__('%s: %s' % (code, message))
        self.code, self.message, self.facts = code, message, facts


def now():
    return datetime.now(timezone.utc).isoformat()


@dataclass(frozen=True)
class Paths:
    home: Path
    keychain: Path
    folder: Path
    password: Path
    record: Path

    @classmethod
    def at(cls, home):
        home = Path(home)
        folder = home / FOLDER
        return cls(home, home / KEYCHAIN, folder, folder / PASSWORD, folder / RECORD)

    def report(self):
        return {'keychain': str(self.keychain), 'folder': str(self.folder), 'password_file': str(self.password),
                'record': str(self.record)}


def requirement(identifier, sha1):
    """The explicit designated requirement a signed binary carries: its identifier and this certificate leaf."""
    return 'identifier "%s" and certificate leaf = H"%s"' % (identifier, sha1.lower())


def requirements(sha1):
    return {kind: requirement(identifier, sha1) for kind, identifier in IDENTIFIERS.items()}


def certificate_sha1(pem):
    """The SHA-1 of the first certificate in PEM text, upper-case as `security find-identity` prints it."""
    text = pem.decode('ascii', 'replace') if isinstance(pem, bytes) else pem
    match = re.search(r'-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----', text, re.S)
    if not match:
        raise Refused('certificate_unreadable', 'No PEM certificate was found.')
    der = base64.b64decode(''.join(match.group(1).split()))
    return hashlib.sha1(der).hexdigest().upper()


def parse_identities(text):
    """[(sha1, name)] from `security find-identity -v` output; the count line and anything else are ignored."""
    found = []
    for line in text.splitlines()[:1000]:
        match = IDENTITY_LINE.match(line)
        if match:
            found.append((match.group(1), match.group(2)))
    return found


def parse_search_list(text):
    """The paths `security list-keychains -d user` prints, one quoted path per line."""
    paths = []
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        if len(line) < 3 or line[0] != '"' or line[-1] != '"' or '"' in line[1:-1]:
            raise Refused('search_list_unparsable', 'The keychain search list has an unexpected line.')
        paths.append(line[1:-1])
    return paths


def redact(data, hidden):
    text = data.decode('utf-8', 'replace') if isinstance(data, bytes) else str(data)
    for value in hidden:
        if value:
            text = text.replace(value, '<redacted>')
    return text[:4000]


def run(argv, stdin=None, timeout=COMMAND_SECONDS, home=None):
    """Run one Apple tool with no shell, a fixed environment and a deadline; returns (exit code, output bytes)."""
    env = {'PATH': '/usr/bin:/bin:/usr/sbin:/sbin', 'LANG': 'C', 'HOME': str(home or Path.home())}
    try:
        done = subprocess.run(argv, input=stdin or b'', stdout=subprocess.PIPE, stderr=subprocess.STDOUT, env=env,
                              cwd='/', timeout=timeout, close_fds=True, start_new_session=True)
    except subprocess.TimeoutExpired:
        return None, b'timed out'
    return done.returncode, done.stdout[:OUTPUT_LIMIT]


def _mode(path):
    try:
        info = os.lstat(path)
    except FileNotFoundError:
        return None
    return {'kind': 'link' if stat.S_ISLNK(info.st_mode) else 'directory' if stat.S_ISDIR(info.st_mode)
            else 'file' if stat.S_ISREG(info.st_mode) else 'other', 'mode': '%04o' % stat.S_IMODE(info.st_mode),
            'owner_only': stat.S_IMODE(info.st_mode) & 0o077 == 0}


def _read_private(path, limit=65536):
    """A regular file owned by this user with no group or other access, read without following a final link."""
    fd = os.open(path, os.O_RDONLY | NOFOLLOW | os.O_NONBLOCK)
    try:
        info = os.fstat(fd)
        if not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid() or stat.S_IMODE(info.st_mode) & 0o077:
            raise Refused('private_file_unsafe', 'A signing file is not a private regular file.', path=str(path))
        return os.read(fd, limit)
    finally:
        os.close(fd)


def _write_private(path, data):
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | NOFOLLOW, 0o600)
    with os.fdopen(fd, 'wb') as stream:
        stream.write(data)
        stream.flush()
        os.fsync(stream.fileno())


def _make_private_folder(paths):
    """~/.pebble (when absent) and ~/.pebble/signing, each 0700; an existing folder or link is never re-moded."""
    missing = [folder for folder in (paths.folder.parent, paths.folder) if not os.path.lexists(folder)]
    for folder in missing:
        os.mkdir(folder, 0o700)
        os.chmod(folder, 0o700)
    if _mode(paths.folder)['kind'] != 'directory':
        raise Refused('folder_not_directory', 'The signing folder is not a directory.', path=str(paths.folder))


def read_record(paths):
    """The identity record (no secrets), or None when absent. A malformed record is refused."""
    try:
        data = _read_private(paths.record)
    except FileNotFoundError:
        return None
    try:
        record = json.loads(data)
    except ValueError:
        raise Refused('record_malformed', 'The identity record is not JSON.', path=str(paths.record)) from None
    if (not isinstance(record, dict) or record.get('format') != RECORD_FORMAT or record.get('name') != NAME
            or not isinstance(record.get('sha1'), str) or not SHA1.fullmatch(record['sha1'])
            or record.get('keychain') != str(paths.keychain)):
        raise Refused('record_malformed', 'The identity record does not describe this identity.', path=str(paths.record))
    return record


