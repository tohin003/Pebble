def file_sha(path):
    """SHA256 of one regular file, never read through a final symlink."""
    fd = os.open(path, os.O_RDONLY | NOFOLLOW | os.O_NONBLOCK)
    try:
        if not stat.S_ISREG(os.fstat(fd).st_mode):
            raise OSError('not a regular file: ' + str(path))
        digest = hashlib.sha256()
        for chunk in iter(lambda: os.read(fd, 1 << 20), b''):
            digest.update(chunk)
        return digest.hexdigest()
    finally:
        os.close(fd)


def write_new(path, value):
    """Create a new file, never replacing one, and return the SHA256 of its bytes."""
    data = value if isinstance(value, bytes) else (json.dumps(value, indent=2) + '\n').encode()
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | NOFOLLOW, 0o600)
    with os.fdopen(fd, 'wb') as stream:
        stream.write(data)
        stream.flush()
        os.fsync(stream.fileno())
    return hashlib.sha256(data).hexdigest()


