        self.node_bin = Path(os.path.abspath(node_bin)) if node_bin else None
        self.runner = runner
        self.verifier = load_verifier(self.root)
        self.rustup_home = Path(os.path.abspath(rustup_home)) if rustup_home else self.root / '.runtime/toolchain/rustup'
        self.cargo_home = Path(os.path.abspath(cargo_home)) if cargo_home else self.root / '.runtime/toolchain/cargo'
        self.toolchain = self.rustup_home / 'toolchains' / TOOLCHAIN / 'bin'
        self.exe = self.out / 'backend/dist/pebble-backend/pebble-backend'
        self.inputs = self.snapshot = self.snapshot_sha = self._written = None

