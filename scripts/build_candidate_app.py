    def env(self, kind='base'):
        """The complete environment of a command; nothing else is inherited."""
        private = {'HOME': str(self.out / 'home'), 'TMPDIR': str(self.out / 'tmp') + '/'}
        if kind == 'native':
            return {'PATH': SYSTEM_PATH, 'LANG': 'C', **private}
        path = [str(self.node_bin or '<node-bin-missing>'), str(self.toolchain),
                str(self.cargo_home / 'bin'), SYSTEM_PATH]
        env = {'PATH': ':'.join(path), 'LANG': 'en_US.UTF-8', 'LC_ALL': 'en_US.UTF-8', **private}
        if kind == 'python':
            env.update(PYINSTALLER_CONFIG_DIR=str(self.out / 'cache/pyinstaller'), PYTHONDONTWRITEBYTECODE='1',
                       PYTHONNOUSERSITE='1', TIKTOKEN_CACHE_DIR=str(self.out / 'cache/tiktoken'),
                       PYTHONHASHSEED='0', SOURCE_DATE_EPOCH=SOURCE_DATE_EPOCH)
        elif kind == 'rust':
            env.update(CARGO_HOME=str(self.cargo_home), RUSTUP_HOME=str(self.rustup_home), RUSTUP_TOOLCHAIN=TOOLCHAIN,
                       RUSTC=str(self.toolchain / 'rustc'), CARGO_TARGET_DIR=str(self.out / 'target'),
                       CARGO_BUILD_JOBS='2', CARGO_ENCODED_RUSTFLAGS=self.remap_flags(),
                       SOURCE_DATE_EPOCH=SOURCE_DATE_EPOCH)
        return env

    def remap_flags(self):
        """V1-023: rustc writes panic locations and debug paths with these prefixes replaced, so the shell carries
        no path of this Mac. CARGO_ENCODED_RUSTFLAGS separates flags with 0x1f, so paths may hold spaces. rustc
        applies the last matching remap, so the outer prefixes come first and the folders inside them after."""
        pairs = [(self.root, '/pebble'), (self.cargo_home, '/cargo'), (self.rustup_home, '/rustup'),
                 (self.out, '/build')]
        pairs.sort(key=lambda pair: len(str(pair[0])))
        return '\x1f'.join('--remap-path-prefix=%s=%s' % (source, target) for source, target in pairs)

    def merge_config(self, kind):
        """The Tauri --config merge for one bundle. In --shell-from-copy mode the copy's own layout supplies the
        frontend and resources, so only the identity and the empty beforeBuildCommand are merged."""
        name, identifier, _ = APPS[kind]
        config = {'identifier': identifier}
        if kind == 'test':
            config['productName'] = name
        if self.copy_mode:
            config['build'] = {'beforeBuildCommand': ''}
        else:
            # Phase 25: Tauri embeds the build config in the shell, so frontendDist is given relative to src-tauri (where
            # Tauri resolves it); an absolute path put this Mac's checkout path into Pebble's binary (machine_paths_in_shell).
            config['build'] = {'beforeBuildCommand': '',
                               'frontendDist': os.path.relpath(self.out / 'frontend/dist', self.root / 'src-tauri')}
            config['bundle'] = {'resources': {'resources/': None, str(self.out / 'stage/resources') + '/': 'resources/'}}
        return config

    def commands(self, step, attempt):
        C, R = self.out, self.root
        python = R / PYTHON

        def command(label, argv, cwd, env, writes=()):
            return {'label': label, 'argv': [str(arg) for arg in argv], 'cwd': str(cwd), 'env': env,
                    'writes': [str(path) for path in writes], 'log': str(C / 'logs' / ('%s.%d.%s.log' % (step, attempt, label)))}
        if step == 'guard-before':
            return [command('version-' + name, argv, C / 'tmp', self.env(kind)) for name, argv, kind in (
                ('python', [python, '--version'], 'python'),
                ('distributions', [python, '-I', '-c', DISTRIBUTIONS], 'python'),
                ('pyinstaller', [python, '-m', 'PyInstaller', '--version'], 'python'),
                ('node', [(self.node_bin or Path('<node-bin-missing>')) / 'node', '--version'], 'base'),
                ('vue-tsc', [self.bin('vue-tsc'), '--version'], 'base'),
                ('vite', [self.bin('vite'), '--version'], 'base'),
                ('tauri', [self.bin('tauri'), '--version'], 'base'),
                ('cargo', [self.toolchain / 'cargo', '--version'], 'rust'),
                ('rustc', [self.toolchain / 'rustc', '--version'], 'rust'))]
        if step == 'backend':
            # The tested spec as is: never --specpath (it would regenerate the spec), never --clean.
            return [command('pyinstaller', [python, '-m', 'PyInstaller', '--noconfirm', '--distpath', C / 'backend/dist',
                                            '--workpath', C / 'backend/work', R / SPEC], C / 'backend', self.env('python'),
                            [C / 'backend/dist', C / 'backend/work', C / 'cache/pyinstaller'])]
        if step == 'frontend':
            dist = C / 'frontend/dist'
            return [command('vue-tsc', [self.bin('vue-tsc'), '--noEmit'], R, self.env()),
                    command('vite-build', [self.bin('vite'), 'build', '--outDir', dist, '--emptyOutDir'], R, self.env(), [dist])]
        if step == 'stage':
            native = self.env('native')
            commands = [command('ditto-backend', [DITTO, self.exe.parent, C / 'stage/resources/backend'], C, native,
                                [C / 'stage/resources/backend'])]
            if self.has_helper():  # read-only: the staged helper still has its pinned cdhash and signer
                commands.append(command('display-helper', [CODESIGN, '--display', '--verbose=4', C / 'stage/resources'
                                                           / signing.HELPER_FOLDER / signing.HELPER_BINARY], C, native))
            if self.identity is not None:  # the per-binary codesign commands depend on the built tree (plan: signing)
                commands.append(command('find-identity', signing.find_argv(self.identity.keychain), C, native))
            if self.copy_mode:
                commands += [command('ditto-shell-resources', [DITTO, C / 'stage/resources', C / 'shell-src/src-tauri/resources'],
                                     C, native, [C / 'shell-src/src-tauri/resources']),
                             command('ditto-shell-dist', [DITTO, C / 'frontend/dist', C / 'shell-src/dist'], C, native,
                                     [C / 'shell-src/dist'])]
            return commands
        if step in ('shell-release', 'shell-test'):
            kind = step.split('-')[1]
            cwd = C / 'shell-src' if self.copy_mode else R
            return [command('tauri-build', [self.bin('tauri'), 'build', '--bundles', 'app', '--config', C / APPS[kind][2],
                                            '--', '--locked', '--offline'], cwd, self.env('rust'), [C / 'target'])]
        if step == 'copy-out':
            native, commands = self.env('native'), []
            if self.identity is not None:
                commands.append(command('find-identity', signing.find_argv(self.identity.keychain), C, native))
            for kind, (name, identifier, _) in APPS.items():
                app = C / kind / (name + '.app')
                commands.append(command('ditto-' + kind, [DITTO, self.built(kind), app], C, native, [app]))
                if self.identity is not None:  # Tauri's flags and entitlements are kept; only the signer changes
                    commands.append(command('sign-' + kind, signing.sign_argv(self.identity, app, identifier,
                                                                              preserve=True), C, native, [app]))
                commands.append(command('codesign-' + kind, [CODESIGN, '--verify', '--deep', '--strict', app], C, native))
                if self.identity is not None:
                    commands += [command('display-' + kind, [CODESIGN, '--display', '--verbose=4', app], C, native),
                                 command('requirements-' + kind, [CODESIGN, '--display', '--requirements', '-', app],
                                         C, native)]
            return commands
        return []

    def outputs(self, step):
        """What a step creates in C; a retried step moves these aside first."""
        C = self.out
        return {'guard-before': [], 'backend': [C / 'backend'], 'frontend': [C / 'frontend'],
                'stage': ([C / 'stage'] + ([C / 'shell-src', C / 'shell-src-manifest.json'] if self.copy_mode else [])
                          + ([C / 'signing'] if self.identity is not None else [])),
                'shell-release': [C / APPS['release'][2], self.built('release')],
                'shell-test': [C / APPS['test'][2], self.built('test')],
                'copy-out': [C / 'release', C / 'test', C / 'app-manifest.json'], 'guard-after': []}[step]

    def _listing(self, base, names):
        found = []
        for name in names:
            entries = {}
            _walk(base, name, entries, lambda path, info: None)
            found += sorted(entries)
        return found

    def writes(self, step):
        """Every path the step writes besides its log and C/inputs.json."""
        C = self.out
        if step == 'backend':
            return [C / 'backend/dist/pebble-backend', C / 'backend/work', C / 'cache/pyinstaller',
                    C / 'backend/candidate-manifest.json']
        if step == 'frontend':
            return [C / 'frontend/dist', C / 'frontend/dist-manifest.json']
        if step == 'stage':
            stage = C / 'stage/resources'
            llama = [] if not self.llama_from.is_dir() else sorted(
                name for name in os.listdir(self.llama_from) if name == 'llama-server' or name.endswith('.dylib'))
            paths = ([stage / 'backend'] + [stage / rel for rel in self._listing(self.root / 'src-tauri/resources',
                                                                                 STAGED_FILES + STAGED_DIRS + OPTIONAL_DIRS)]
                     + [stage / 'llama'] + [stage / 'llama' / name for name in llama] + [C / 'stage/stage-manifest.json'])
            if self.has_extension():
                paths += [stage / rel for rel in self._listing(self.root, (EXTENSION,))
                          if not rel.endswith(EXTENSION_SKIP)]
            if self.copy_mode:
                shell = C / 'shell-src'
                names = [n for n in sorted(os.listdir(self.root / 'src-tauri')) if n not in SHELL_SKIP] if (self.root / 'src-tauri').is_dir() else []
                paths += ([shell / 'src-tauri' / rel for rel in self._listing(self.root / 'src-tauri', names)]
                          + [shell / name for name in SHELL_TOP]
                          + [shell / 'src-tauri/resources', shell / 'dist', C / 'shell-src-manifest.json'])
            if self.identity is not None:  # each Mach-O is signed as a copy here, then put in place
                paths += [C / 'signing'] + ([C / 'signing/backend.entitlements'] if self.hardened_backend else [])
            return paths
        if step in ('shell-release', 'shell-test'):
            kind = step.split('-')[1]
            extra = [C / 'shell-src/src-tauri/gen'] if self.copy_mode else []
            return [C / APPS[kind][2], C / 'target', self.built(kind)] + extra
        if step == 'copy-out':
            return [C / kind / (APPS[kind][0] + '.app') for kind in APPS] + [C / 'app-manifest.json']
        return []

    # ---- Read-only checks ----------------------------------------------------------------------

    def _check_out(self, resume):
        C = self.out
        if not C.parent.is_dir():
            raise Refused('out_parent_missing', [self.display(C.parent)])
        if within(C, self.root) and not within(C, self.root / '.runtime'):
            raise Refused('out_inside_checkout', [self.display(C)], 'C must be under <root>/.runtime or outside the checkout.')
        if within(self.root, C):
            raise Refused('out_contains_root', [C])
        if not self.copy_mode and GLOB.search(str(C)):
            raise Refused('out_path_is_a_glob', [C], 'Tauri reads resource sources as glob patterns.')
        if resume:
            if not (C / 'inputs.json').is_file():
                raise Refused('resume_without_inputs', [self.display(C / 'inputs.json')])
        elif os.path.lexists(C):
            raise Refused('out_exists', [self.display(C)])

    def _load_snapshot(self):
        if self.snapshot_path is None:
            raise Refused('snapshot_missing', [], '--snapshot <tested-source.json> is required.')
        try:
            data = self.snapshot_path.read_bytes()
            snapshot = json.loads(data)
        except (OSError, ValueError):
            raise Refused('snapshot_unreadable', [self.display(self.snapshot_path)]) from None
        if not isinstance(snapshot, dict) or not all(
                isinstance(value, str) and re.fullmatch('[0-9a-f]{64}', value) for value in snapshot.values()):
            raise Refused('snapshot_malformed', [self.display(self.snapshot_path)])
        self.snapshot, self.snapshot_sha = snapshot, hashlib.sha256(data).hexdigest()

    def _check_sources(self):
        try:
            current = self.verifier.sources()
        except FileNotFoundError as error:
            raise Refused('source_unreadable', [self.display(error.filename)]) from None
        differ = sorted(name for name in current.keys() | self.snapshot.keys() if current.get(name) != self.snapshot.get(name))
        if differ:
            raise Refused('source_differs_from_snapshot', differ, {'snapshot': self.display(self.snapshot_path)})

    def _check_imported(self):
        differ = [rel for rel in IMPORTED if self.snapshot.get(rel) != file_sha(TOOL_ROOT / rel)]
        if differ:
            raise Refused('tool_differs_from_snapshot', differ, 'The code this tool runs is not the tested code.')

    def _check_spec(self):
        try:
            text = (self.root / SPEC).read_text()
        except OSError:
            raise Refused('spec_missing', [SPEC]) from None
        outside = sorted({path for path in re.findall(r"""['"](/[^'"\n]+)['"]""", text)
                          if not within(os.path.realpath(path), self.root)})
        if outside:
            raise Refused('spec_outside_root', outside, 'The spec would freeze sources from another checkout.')

    def _check_lock(self):
        """V1-076: the lock pins every requirement at its version and every pin has a hash; the toolchain pin
        names TOOLCHAIN (V1-048)."""
        try:
            facts = packaging.lock_check(self.root / LOCK, self.root / 'backend/requirements.txt')
        except OSError:
            raise Refused('lock_missing', [LOCK]) from None
        except packaging.Refused as error:
            raise Refused('lock_unreadable', [LOCK], {'code': error.code, 'detail': error.detail}) from None
        if facts['differences']:
            raise Refused('lock_differs_from_requirements', [LOCK], {'differences': facts['differences']})
        if facts['unhashed']:
            raise Refused('lock_unhashed', [LOCK], 'Run scripts/package_backend.py lock-hashes --write, then '
                          'build-env (docs/HARNESS_CANDIDATE_APP.md). Unhashed: ' + ', '.join(facts['unhashed'][:12]))
        try:
            channel = toolchain_channel((self.root / TOOLCHAIN_PIN).read_text())
        except OSError:
            channel = None
        if channel is None or not TOOLCHAIN.startswith(channel + '-'):
            raise Refused('toolchain_pin_differs', [TOOLCHAIN_PIN], {'expected': TOOLCHAIN, 'channel': channel})

    def _check_build_env(self, text):
        """The build environment's distributions are exactly the lock's pins (plus what venv adds)."""
        try:
            installed = {packaging.normalize(name): version for name, version in json.loads(text)}
        except (ValueError, TypeError):
            raise Refused('build_env_unreadable', [PYTHON]) from None
        pins = {packaging.normalize(pin['name']): pin['version']
                for pin in packaging.read_lock((self.root / LOCK).read_text())}
        differences = [{'name': name, 'lock': pins.get(name), 'installed': installed.get(name)}
                       for name in sorted(pins.keys() | installed.keys())
                       if pins.get(name) != installed.get(name) and not (name not in pins and name in LOCK_EXTRAS)]
        if differences:
            raise Refused('build_env_differs_from_lock', [PYTHON, LOCK], {'differences': differences[:200]})
        return len(pins)

    def _check_tools(self):
        tools = [self.root / PYTHON, self.bin('vue-tsc'), self.bin('vite'), self.bin('tauri'),
                 self.toolchain / 'cargo', self.toolchain / 'rustc', Path(DITTO), Path(CODESIGN)]
        missing = [] if self.node_bin else ['node (no --node-bin and none on PATH)']
        tools += [self.node_bin / 'node'] if self.node_bin else []
        tools += [Path(SECURITY)] if self.identity is not None else []
        missing += [self.display(tool) for tool in tools if not (os.path.isfile(tool) and os.access(tool, os.X_OK))]
        if missing:
            raise Refused('tool_missing', missing)

    def _check_identity(self):
        """The identity's record, keychain and password file are still there (its validity is checked by
        security find-identity before anything is signed)."""
        if self.identity is None:
            return
        paths = self.identity.paths
        missing = [str(path) for path in (paths.keychain, paths.password, paths.record) if not os.path.lexists(path)]
        if missing:
            raise Refused('signing_identity_unavailable', missing, 'Create it with scripts/pebble_signing.py, or '
                          'build with --identity adhoc.')

    def _check_resources(self):
        source = self.root / 'src-tauri/resources'
        names = set(os.listdir(source)) if source.is_dir() else set()
        missing = [name for name in STAGED_FILES + STAGED_DIRS if name not in names]
        if missing:
            raise Refused('resource_missing', [self.display(source / name) for name in missing])
        unexpected = sorted(names - set(STAGED_FILES + STAGED_DIRS + REPLACED + OPTIONAL_DIRS))
        if unexpected:
            raise Refused('unexpected_resource', [self.display(source / name) for name in unexpected],
                          'Neither staged nor known; review it before building.')
        try:  # the pinned helper equals its manifest and source, and (when signing) has this build's signer
            self.helper_manifest = signing.check_pinned_helper(self.root, self.identity)
        except signing.Refused as error:
            raise Refused(error.code, [self.display(source / signing.HELPER_FOLDER)],
                          {key: value for key, value in error.facts.items() if key != 'path'}) from None
        bad = tokenizer_problem(source / 'tokenizer')
        if bad:
            raise Refused('tokenizer_mismatch', [self.display(bad)], {'expected_sha256': TOKENIZER_SHA256})
        if not os.path.lexists(self.llama_from / 'llama-server'):
            raise Refused('llama_server_missing', [self.display(self.llama_from / 'llama-server')])

    def preflight(self, resume=False):
        """Every problem execute would refuse on before writing anything, in that order."""
        problems, self.snapshot, self.snapshot_sha = [], None, None
        if sys.platform != 'darwin':
            problems.append(Refused('unsupported_platform', [], sys.platform).report())
        for check in (lambda: self._check_out(resume), self._load_snapshot, self._check_sources, self._check_imported,
                      self._check_spec, self._check_lock, self._check_tools, self._check_resources, self._check_identity):
            if self.snapshot is None and check in (self._check_sources, self._check_imported):
                continue  # needs the snapshot, whose own problem is already listed
            try:
                check()
            except Refused as error:
                problems.append(error.report())
        return problems

    def _unmet(self, steps, done):
        ready, unmet = set(done), []
        for step in STEPS:
            if step in steps and step not in done:
                unmet += [prior for prior in STEPS[:STEPS.index(step)] if prior not in ready and prior not in unmet]
                ready.add(step)
        return unmet

    def plan(self, steps=STEPS, resume=False):
        """What execute would run and write; reads only."""
        problems, done, attempts = self.preflight(resume), set(), {}
        if resume:
            try:
                recorded = json.loads((self.out / 'inputs.json').read_bytes())['steps']
                done = {step for step in STEPS if recorded[step]['status'] == 'done'}
                attempts = {step: len(recorded[step]['attempts']) for step in STEPS}
            except (OSError, ValueError, KeyError, TypeError):
                pass
        unmet = self._unmet(steps, done)
        if unmet:
            problems.append(Refused('steps_out_of_order', unmet).report())
        planned = []
        for step in STEPS:
            if step in steps and step not in done:
                commands = self.commands(step, attempts.get(step, 0) + 1)
                for command in commands:
                    try:
                        check_command(command, self.root, self.out)
                    except Refused as error:
                        problems.append(error.report())
                planned.append({'step': step,
                                'commands': [{key: command[key] for key in ('label', 'argv', 'cwd', 'env', 'log')}
                                             for command in commands],
                                'writes': [str(path) for path in self.writes(step)],
                                'moves_aside_if_present': [str(path) for path in self.outputs(step)]})
        C = self.out
        return {'mode': 'plan', 'tool': str(TOOL), 'root': str(self.root), 'out': str(C),
                'shell_mode': 'shell-from-copy' if self.copy_mode else 'merge-config',
                'llama_from': str(self.llama_from), 'node_bin': str(self.node_bin), 'snapshot': str(self.snapshot_path),
                'creates': [] if resume else [str(path) for path in (C, C / 'inputs.json', C / '.build.lock', C / 'logs',
                                                                    C / 'home', C / 'tmp', C / 'cache', C / 'aside')],
                'guard': {'hashed': list(GUARDED), 'statted': list(STATTED), 'rechecked': 'after every step'},
                'merge_configs': {str(C / APPS[kind][2]): self.merge_config(kind) for kind in APPS},
                'signing': self.signing_plan(), 'steps': planned, 'problems': problems,
                'browser_extension': ({'staged': 'stage/resources/' + EXTENSION + ', read-only from the checkout, '
                                                 'without ' + ', '.join('*' + s for s in EXTENSION_SKIP),
                                       'checked': 'each staged file against its source (stage_copy_differs)'}
                                      if self.has_extension() else None),
                'vault_helper': ({'staged': 'stage/resources/helpers, byte for byte, never re-signed',
                                  'checked': 'its manifest, its source SHA-256, its signer and (codesign --display) its '
                                             'cdhash', 'manifest': self.helper_manifest}
                                 if self.has_helper() else None)}

    def signing_identity(self):
        """What inputs.json records about the signer (a resumed build must use the same one); None is ad hoc."""
        if self.identity is None:
            return None
        return dict(self.identity.describe(), hardened_backend=self.hardened_backend)

    def signing_plan(self):
        """How this build signs. The per-binary backend commands depend on the built tree, so they are shown as a
        template: one codesign per Mach-O, deepest first and the executable last, each on a copy in C/signing."""
        if self.identity is None:
            return {'mode': 'adhoc', 'detail': "Tauri's ad-hoc signature (signingIdentity \"-\"); nothing is re-signed."}
        C, entitlements = self.out, self.out / 'signing/backend.entitlements'
        return {'mode': 'local_identity', 'identity': self.identity.describe(),
                'unlock': 'pebble_signing.unlock: security unlock-keychain on the identity keychain (password from its '
                          '0600 file; never logged)',
                'designated_requirements': {kind: self.identity.requirement(identifier) for kind, identifier in
                                            (('release', APPS['release'][1]), ('test', APPS['test'][1]),
                                             ('backend', signing.IDENTIFIERS['backend']))},
                'backend': {'template': signing.sign_argv(
                    self.identity, C / 'signing/backend/<NNNN>/<name>', '<identifier>', runtime=self.hardened_backend,
                    entitlements=entitlements if self.hardened_backend else None),
                    'identifiers': '%s for pebble-backend; %s.<path with / as .> for the others'
                                   % (signing.IDENTIFIERS['backend'], signing.IDENTIFIERS['backend']),
                    'hardened_runtime': self.hardened_backend,
                    'entitlements': BACKEND_ENTITLEMENTS if self.hardened_backend else None,
                    'then': ['codesign --verify --strict (all copies)', 'codesign --display --verbose=4 (cdhashes)',
                             'codesign --display --requirements - (the executable)', 'each copy replaces its file']},
                'apps': 'sign-<kind> in copy-out: the bundle with --preserve-metadata=entitlements,flags,runtime'}

    # ---- Execution -----------------------------------------------------------------------------

    def _identity(self):
        record = {'schema': SCHEMA, 'root': str(self.root), 'out': str(self.out),
                  'shell_mode': 'shell-from-copy' if self.copy_mode else 'merge-config',
                  'llama_from': str(self.llama_from), 'node_bin': str(self.node_bin),
                  'allow_flattened_links': self.allow_flattened, 'tool': {'path': str(TOOL), 'sha256': file_sha(TOOL)},
                  'source_snapshot': {'path': str(self.snapshot_path), 'sha256': self.snapshot_sha, 'files': len(self.snapshot)},
                  'imported_code_sha256': {rel: file_sha(TOOL_ROOT / rel) for rel in IMPORTED}}
        if self.identity is not None:  # absent for ad hoc, so an ad-hoc inputs.json reads as before
            record['signing'] = self.signing_identity()
        return record

    def execute(self, steps=STEPS, resume=False):
        problems = self.preflight(resume)
        if problems:
            first = problems[0]
            raise Refused(first['refused'], first['paths'],
                          {'detail': first['detail'], 'more': problems[1:]} if len(problems) > 1 else first['detail'])
        if resume:
            self._load()
        done = {step for step in STEPS if self.inputs and self.inputs['steps'][step]['status'] == 'done'}
        unmet = self._unmet(steps, done)
        if unmet:
            raise Refused('steps_out_of_order', unmet, 'Earlier steps must be done first.')
        if not resume:
            self._create()
        todo = [step for step in STEPS if step in steps and step not in done]
        with self._locked():
            if resume and todo:
                self._check_unchanged()
            for step in todo:
                self._run_step(step)
        result = {'out': str(self.out), 'ran': todo, 'result': self.inputs['result'],
                  'done': [step for step in STEPS if self.inputs['steps'][step]['status'] == 'done']}
        if self.inputs['steps']['copy-out']['status'] == 'done':
            result.update(self.evidence('copy-out'))
        return result

    def _create(self):
        C = self.out
        try:
            os.mkdir(C, 0o700)
        except FileExistsError:
            raise Refused('out_exists', [self.display(C)]) from None
        os.chmod(C, 0o700)
        for name in ('logs', 'home', 'tmp', 'cache', 'aside'):
            os.mkdir(C / name, 0o700)
        write_new(C / '.build.lock', b'')
        self.inputs = dict(self._identity(), created_at=now(), tool_versions=None, guard={'before': None, 'after': None},
                           steps={step: {'status': 'pending', 'attempts': []} for step in STEPS}, failure=None, result=None)
        self._written = write_new(C / 'inputs.json', self.inputs)

    def _load(self):
        path = self.out / 'inputs.json'
        data = path.read_bytes()
        try:
            inputs = json.loads(data)
        except ValueError:
            raise Refused('inputs_malformed', [self.display(path)]) from None
        differ = [key for key, value in self._identity().items() if inputs.get(key) != value]
        if 'signing' not in differ and inputs.get('signing') != self.signing_identity():  # also signed -> ad hoc
            differ.append('signing')
        if differ:
            raise Refused('resume_mismatch', differ, {'recorded': {key: inputs.get(key) for key in differ}})
        self.inputs, self._written = inputs, hashlib.sha256(data).hexdigest()

    def _save(self):
        """Replace inputs.json atomically. Its history is append-only (attempts are never removed), and a copy
        changed by anyone else is refused rather than overwritten."""
        path = self.out / 'inputs.json'
        try:
            current = file_sha(path)
        except OSError:
            current = None
        if current != self._written:
            raise Refused('inputs_changed_externally', [self.display(path)])
        data = (json.dumps(self.inputs, indent=2) + '\n').encode()
        temporary = self.out / ('.inputs.%d.%s.json' % (os.getpid(), os.urandom(6).hex()))
        write_new(temporary, data)
        os.replace(temporary, path)
        self._written = hashlib.sha256(data).hexdigest()

    @contextlib.contextmanager
    def _locked(self):
        path = self.out / '.build.lock'
        fd = os.open(path, os.O_RDWR | NOFOLLOW)
        try:
            try:
                fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except OSError:
                raise Refused('build_locked', [self.display(path)]) from None
            yield
        finally:
            os.close(fd)

    def evidence(self, step):
        return self.inputs['steps'][step]['attempts'][-1]['evidence']

    def _check_unchanged(self):
        before = self.inputs['guard']['before']
        if before is not None:
            changes = guard_changes(before, guard_state(self.root))
            paths = sorted(changes['changed'] + changes['added'] + changes['removed'])
            if paths:
                raise Refused('shared_paths_changed', paths, changes)
        self._check_sources()

    def _run_step(self, step):
        entry = self.inputs['steps'][step]
        record = {'attempt': len(entry['attempts']) + 1, 'started_at': now(), 'status': 'running', 'logs': [],
                  'moved_aside': []}
        entry['attempts'].append(record)
        entry['status'] = 'running'
        self._save()
        try:
            self._move_aside(step, record)
            record['evidence'] = getattr(self, '_step_' + step.replace('-', '_'))(record)
            if step not in ('guard-before', 'guard-after'):
                self._check_unchanged()
        except BaseException as error:
            failure = (error.report() if isinstance(error, Refused)
                       else {'refused': 'crashed', 'paths': [], 'detail': repr(error)[:2000]})
            record.update(status='failed', finished_at=now(), failure=failure)
            entry['status'] = 'failed'
            self.inputs['failure'] = dict(failure, step=step, attempt=record['attempt'])
            self._save()
            raise
        record.update(status='done', finished_at=now())
        entry['status'] = 'done'
        self.inputs['failure'] = None
        self._save()

    def _move_aside(self, step, record):
        for path in self.outputs(step):
            if os.path.lexists(path):
                folder = self.out / 'aside' / ('%s.attempt%d' % (step, record['attempt'] - 1))
                os.makedirs(folder, 0o700, exist_ok=True)
                target = folder / path.name
                if os.path.lexists(target):
                    raise Refused('aside_exists', [self.display(target)])
                os.rename(path, target)
                record['moved_aside'].append({'from': self.display(path), 'to': self.display(target)})

    def _run(self, record, command):
        check_command(command, self.root, self.out)
        log = Path(command['log'])
        fd = os.open(log, os.O_WRONLY | os.O_CREAT | os.O_EXCL | NOFOLLOW, 0o600)
        record['logs'].append(self.display(log))
        with os.fdopen(fd, 'wb') as stream:
            code = self.runner(list(command['argv']), command['cwd'], dict(command['env']), stream)
        if code != 0:
            raise Refused('command_failed', [self.display(log)], {'label': command['label'], 'exit_code': code})
        return log

    def _commands(self, step, record):
        return {command['label']: command for command in self.commands(step, record['attempt'])}

    def _run_batch(self, record, step, label, argvs, writes=()):
        """Run commands known only at run time (one per backend binary) into ONE new log, each preceded by its argv.
        Each is checked like a planned command; the first failure stops the step. writes[i] is what argvs[i] writes."""
        log = self.out / 'logs' / ('%s.%d.%s.log' % (step, record['attempt'], label))
        fd = os.open(log, os.O_WRONLY | os.O_CREAT | os.O_EXCL | NOFOLLOW, 0o600)
        record['logs'].append(self.display(log))
        env = self.env('native')
        with os.fdopen(fd, 'wb') as stream:
            for index, argv in enumerate(argvs):
                command = {'label': label, 'argv': [str(arg) for arg in argv], 'cwd': str(self.out), 'env': env,
                           'writes': [str(writes[index])] if writes else []}
                check_command(command, self.root, self.out)
                stream.write(('$ %s\n' % shlex.join(command['argv'])).encode())
                stream.flush()
                code = self.runner(list(command['argv']), command['cwd'], dict(env), stream)
                if code != 0:
                    raise Refused('command_failed', [self.display(log)], {'label': label, 'exit_code': code,
                                                                         'command': index})
        return log

    def _check_identity_valid(self, log):
        """security find-identity -v lists this identity as valid for code signing in its keychain."""
        valid = signing.parse_identities(read_text(log, 1 << 20))
        if (self.identity.sha1, self.identity.name) not in valid:
            raise Refused('signing_identity_unavailable', [str(self.identity.keychain)],
                          {'expected': self.identity.describe(), 'valid': [{'sha1': sha, 'name': name}
                                                                           for sha, name in valid]})

    @contextlib.contextmanager
    def _unlocked(self, record):
        """The identity keychain is open only while codesign signs: while it is open, any process of this user could
        sign as Pebble and inherit Pebble's privacy grants. It is locked again even when signing fails."""
        try:
            self.unlock()
        except signing.Refused as error:  # its facts are redacted; the password is never in them
            raise Refused('signing_keychain_locked', [str(self.identity.keychain)],
                          {'code': error.code, 'message': error.message}) from None
        try:
            yield
        finally:
            try:
                self.lock()
            except signing.Refused as error:  # it still locks itself after pebble_signing.LOCK_SECONDS
                record.setdefault('warnings', []).append({'keychain_not_relocked': error.code})

    def _signature(self, blocks, path, identifier):
        """The display block of one signed path, checked: identifier, this identity as the only authority, no team,
        a cdhash, and (when shown) the explicit designated requirement."""
        block = blocks.get(str(path))
        expected = self.identity.requirement(identifier)
        problems = [] if block else ['not_displayed']
        if block:
            if block['identifier'] != identifier:
                problems.append('identifier')
            if block['authorities'] != [self.identity.name]:
                problems.append('authority')
            if not block['cdhash'] or not re.fullmatch(r'[0-9a-f]{40}', block['cdhash']):
                problems.append('cdhash')
            if block['team'] not in (None, 'not set'):
                problems.append('team')
            if {'adhoc', 'linker-signed'} & set(block['flags']):  # e.g. a flag carried over from Tauri's signature
                problems.append('adhoc_flag')
            if block['designated'] is not None and not signing.same_requirement(block['designated'], expected):
                problems.append('designated_requirement')
        if problems:
            raise Refused('signature_unexpected', [self.display(path)], {'problems': problems, 'shown': block})
        return block

    def _stage_helper(self, record, commands, resources):
        """The pinned vault helper, staged byte for byte (stage_copy_differs already compared it with its source):
        its manifest still matches, and codesign shows the pinned cdhash, identifier and signer with the hardened
        runtime. It is never re-signed: a new code hash would make every Mac ask again."""
        pinned = self.helper_manifest
        staged = resources / signing.HELPER_FOLDER / signing.HELPER_BINARY
        if pinned is None or file_sha(staged) != pinned['sha256']:
            raise Refused('vault_helper_differs', [self.display(staged)],
                          {'expected': (pinned or {}).get('sha256'), 'actual': file_sha(staged)})
        shown = signing.parse_codesign_blocks(read_text(self._run(record, commands['display-helper'])))
        block = shown.get(str(staged)) or {}
        problems = [name for name, ok in (
            ('cdhash', block.get('cdhash') == pinned['cdhash']),
            ('identifier', block.get('identifier') == pinned['identifier'] == signing.IDENTIFIERS['helper']),
            ('authority', block.get('authorities') == [(pinned['identity'] or {}).get('name')]),
            ('hardened_runtime', 'runtime' in (block.get('flags') or [])),
            ('adhoc_flag', not {'adhoc', 'linker-signed'} & set(block.get('flags') or []))) if not ok]
        if problems:
            raise Refused('vault_helper_signature_differs', [self.display(staged)],
                          {'problems': problems, 'pinned_cdhash': pinned['cdhash'], 'shown': block})
        return {'path': signing.HELPER_FOLDER + '/' + signing.HELPER_BINARY, 'sha256': pinned['sha256'],
                'cdhash': pinned['cdhash'], 'identifier': pinned['identifier'],
                'designated_requirement': pinned['designated_requirement'],
                'identity_sha1': (pinned['identity'] or {}).get('sha1'), 'source_sha256': pinned['source']['sha256'],
                'resigned': False}

    def _sign_backend(self, record, commands, backend):
        """Sign every Mach-O of the staged backend with the identity, deepest first and the executable last. Each is
        signed as a copy in C/signing/backend (in place, codesign would sign a framework's binary as its bundle and
        add a _CodeSignature folder), verified and displayed, and only then put in place with its mode."""
        self._check_identity_valid(self._run(record, commands['find-identity']))
        found = []
        for directory, folders, files in os.walk(backend):
            folders.sort()
            for name in sorted(files):
                path = Path(directory, name)
                with open(path, 'rb') as stream:
                    if is_macho(stream.read(8)):
                        found.append(path.relative_to(backend).as_posix())
        found.sort(key=lambda rel: (rel == 'pebble-backend', -rel.count('/'), rel))
        if 'pebble-backend' not in found:
            raise Refused('backend_missing', [self.display(backend / 'pebble-backend')])
        work = self.out / 'signing/backend'
        os.mkdir(work, 0o700)
        entitlements = None
        if self.hardened_backend:
            entitlements = self.out / 'signing/backend.entitlements'
            write_new(entitlements, plistlib.dumps(BACKEND_ENTITLEMENTS))
        copies, argvs, unsigned = [], [], {}
        for index, rel in enumerate(found):
            os.mkdir(work / ('%04d' % index), 0o700)
            copy = work / ('%04d' % index) / PurePosixPath(rel).name
            unsigned[rel] = file_sha(backend / rel)
            copy_entry(backend / rel, copy, {}, rel)
            copies.append(copy)
            argvs.append(signing.sign_argv(self.identity, copy, backend_identifier(rel), runtime=self.hardened_backend,
                                           entitlements=entitlements))
        with self._unlocked(record):
            self._run_batch(record, 'stage', 'sign-backend', argvs, copies)
        self._run_batch(record, 'stage', 'verify-backend', [[CODESIGN, '--verify', '--strict', '--verbose=2', *copies]])
        shown = signing.parse_codesign_blocks(read_text(self._run_batch(
            record, 'stage', 'display-backend', [[CODESIGN, '--display', '--verbose=4', *copies]]), 16 << 20))
        designated = signing.parse_codesign_blocks(read_text(self._run_batch(
            record, 'stage', 'requirements-backend', [[CODESIGN, '--display', '--requirements', '-', copies[-1]]])))
        files = []
        for rel, copy in zip(found, copies):
            block = dict(self._signature(shown, copy, backend_identifier(rel)))
            if rel == 'pebble-backend':
                block['designated'] = designated.get(str(copy), {}).get('designated')
                self._signature({str(copy): block}, copy, backend_identifier(rel))
                if block['designated'] is None:
                    raise Refused('signature_unexpected', [self.display(copy)], {'problems': ['designated_requirement']})
            os.chmod(copy, stat.S_IMODE(os.lstat(backend / rel).st_mode))
            files.append({'path': 'backend/' + rel, 'identifier': backend_identifier(rel), 'cdhash': block['cdhash'],
                          'flags': block['flags'], 'unsigned_sha256': unsigned[rel], 'sha256': file_sha(copy)})
        for rel, copy in zip(found, copies):
            os.replace(copy, backend / rel)
        executable = files[-1]
        return {'mode': 'local_identity', 'identity': self.identity.describe(),
                'hardened_runtime': self.hardened_backend, 'files': files,
                'executable': {'path': executable['path'], 'identifier': executable['identifier'],
                               'cdhash': executable['cdhash'], 'sha256': executable['sha256'],
                               'designated_requirement': self.identity.requirement(executable['identifier'])}}

    # ---- Steps ---------------------------------------------------------------------------------

    def _step_guard_before(self, record):
        versions = {}
        for command in self.commands('guard-before', record['attempt']):
            name = command['label'][len('version-'):]
            versions[name] = read_text(self._run(record, command), 1 << 20 if name == 'distributions' else 4096).strip()
        pins = self._check_build_env(versions['distributions'])
        state = guard_state(self.root)
        self.inputs['tool_versions'], self.inputs['guard']['before'] = versions, state
        return {'tool_versions': versions, 'hashed': len(state['hashes']), 'statted': len(state['stats']),
                'absent': state['absent'], 'build_env_matches_lock': {'lock': LOCK, 'pins': pins}}

    def _candidate_manifest(self):
        path = list(sys.path)
        try:
            return self.verifier.candidate_manifest(self.exe)
        except (RuntimeError, ValueError, OSError) as error:
            raise Refused('backend_unsafe', [self.display(self.exe.parent)], str(error)[:2000]) from None
        finally:
            sys.path[:] = path  # candidate_manifest prepends <root>/backend

    def _step_backend(self, record):
        os.mkdir(self.out / 'backend', 0o700)
        log = self._run(record, self._commands('backend', record)['pyinstaller'])
        if not os.path.isfile(self.exe) or os.path.islink(self.exe):
            raise Refused('backend_missing', [self.display(self.exe)])
        manifest = self._candidate_manifest()
        manifest_sha = write_new(self.out / 'backend/candidate-manifest.json', manifest)
        # D20 §8 open check 8: UPX-packed Mach-O cannot be signed. Refuse packed files; record the log's UPX line.
        packed = []
        for entry in manifest['files']:
            with open(self.exe.parent / entry['path'], 'rb') as stream:
                head = stream.read(65536)
            if head[:4] in MACHO and b'UPX!' in head:
                packed.append(self.display(self.exe.parent / entry['path']))
        if packed:
            raise Refused('upx_packed', packed)
        copyleft = sorted(entry['path'] for entry in manifest['files'] if COPYLEFT_BINARY.search(entry['path']))
        if copyleft:  # V1-045: HEIC is macOS's job; the HEIF stack's GPL/LGPL libraries never ship
            raise Refused('copyleft_binary_in_backend', [self.display(self.exe.parent / rel) for rel in copyleft[:50]])
        # What ships: the stage flattens the dist's links (Tauri's resource copy drops them), so the bundled backend
        # is this view, the tree package_backend.py's copytree made for 0.4.2.
        flat = flat_manifest(self.exe.parent, 'backend_unsafe', self.display(self.exe.parent))
        text = read_text(log)
        return {'executable': self.display(self.exe), 'executable_sha256': file_sha(self.exe),
                'candidate_bundle_sha256': manifest['bundle_sha256'], 'file_count': len(manifest['files']),
                'flattened_bundle_sha256': flat['bundle_sha256'], 'flattened_file_count': flat['file_count'],
                'links': len(flat['flattened']), 'links_sha256': links_digest(flat['flattened']),
                'directory_links': sum(link['kind'] == 'directory' for link in flat['flattened']),
                'bytes': sum(entry['bytes'] for entry in manifest['files']), 'candidate_manifest_sha256': manifest_sha,
                'upx_log': ('available' if 'UPX is available' in text else
                            'not_available' if 'UPX is not available' in text else 'unknown'),
                'pillow_heif_files': sum('pillow_heif' in entry['path'] for entry in manifest['files']),
                'copyleft_binaries': 0}

    def _step_frontend(self, record):
        os.mkdir(self.out / 'frontend', 0o700)
        for command in self.commands('frontend', record['attempt']):
            self._run(record, command)
        dist = self.out / 'frontend/dist'
        manifest = tree_manifest(dist, 'frontend_unsafe')
        if 'index.html' not in {entry['path'] for entry in manifest['files']}:
            raise Refused('frontend_incomplete', [self.display(dist / 'index.html')])
        return {'dist_sha256': manifest['bundle_sha256'], 'file_count': manifest['file_count'],
                'dist_manifest_sha256': write_new(self.out / 'frontend/dist-manifest.json', manifest)}

    def _step_stage(self, record):
        C, source = self.out, self.root / 'src-tauri/resources'
        backend = self.evidence('backend')
        if self._candidate_manifest()['bundle_sha256'] != backend['candidate_bundle_sha256']:
            raise Refused('backend_output_changed', [self.display(self.exe.parent)])
        dist = flat_manifest(self.exe.parent, 'backend_unsafe', self.display(self.exe.parent))
        if (dist['bundle_sha256'], links_digest(dist['flattened'])) != (backend['flattened_bundle_sha256'],
                                                                       backend['links_sha256']):
            raise Refused('backend_output_changed', [self.display(self.exe.parent)])
        resources = C / 'stage/resources'
        os.mkdir(C / 'stage', 0o700)
        os.mkdir(resources, 0o755)
        commands = self._commands('stage', record)
        self._run(record, commands['ditto-backend'])
        # Tauri's resource copy drops symlinks (the first real build lost all 22, Python included), so the staged
        # backend holds what each link names, as package_backend.py's copytree shipped 0.4.2. The dist keeps its links.
        flattened = flatten_links(resources / 'backend', 'stage_link_unsafe', self.display(resources), 'backend/')
        sources, skipped = {}, []
        for name in STAGED_FILES + STAGED_DIRS + tuple(name for name in OPTIONAL_DIRS if os.path.lexists(source / name)):
            copy_entry(source / name, resources / name, sources, name)
        if self.has_extension():
            copy_entry(self.root / EXTENSION, resources / EXTENSION, sources, EXTENSION, skip=EXTENSION_SKIP)
        os.mkdir(resources / 'llama', 0o755)
        for name in sorted(os.listdir(self.llama_from)):
            if name == 'llama-server' or name.endswith('.dylib'):  # package_backend.py's selection
                copy_entry(self.llama_from / name, resources / 'llama' / name, sources, 'llama/' + name)
            else:
                skipped.append(name)
        if tokenizer_problem(resources / 'tokenizer'):
            raise Refused('tokenizer_mismatch', [self.display(source / 'tokenizer' / TOKENIZER_FILE)],
                          {'expected_sha256': TOKENIZER_SHA256, 'staged': self.display(resources / 'tokenizer' / TOKENIZER_FILE)})

        def origin(rel):
            if rel.startswith('backend/'):
                return self.display(self.exe.parent / rel[len('backend/'):])
            return self.display(sources[rel]) if rel in sources else None
        try:
            tree = tree_manifest(resources, 'stage_unsafe')
        except Refused as error:  # report links that leave the stage by their source paths
            if isinstance(error.detail, dict) and 'problems' in error.detail:
                error.paths = sorted(origin(path) or path for path in error.paths)
            raise
        # Exact against the dist's flattened view: content and mode per path, no links on either side, and the
        # replaced links are the dist's own.
        differences, _ = tree_differences(dist, subtree(tree, 'backend'))
        want, have = ({link['path']: link for link in links} for links in (dist['flattened'], flattened))
        differences += [{'path': path, 'problem': 'flattened_link_differs', 'expected': want.get(path),
                         'actual': have.get(path)}
                        for path in sorted(want.keys() | have.keys()) if want.get(path) != have.get(path)]
        if differences:
            differences.sort(key=lambda item: item['path'])
            raise Refused('staged_backend_differs', sorted({'backend/' + item['path'] for item in differences}),
                          {'differences': differences[:200]})
        linked = {link['path'] for link in tree['links']}
        for entry in tree['files']:
            rel = entry['path']
            if not rel.startswith('backend/') and rel not in linked and file_sha(sources[rel]) != entry['sha256']:
                raise Refused('stage_copy_differs', [self.display(sources[rel])])
        # V1-023: no binary or archive that ships may carry this Mac's paths. Every staged backend and llama file is
        # scanned, base_library.zip member by member; the generic /Users/ count is recorded for review.
        scan = machine_path_scan(resources, self.needles(),
                                 {entry['path'] for entry in tree['files']
                                  if entry['path'].startswith(('backend/', 'llama/'))})
        if scan['machine']:
            raise Refused('machine_paths_in_stage', scan['paths'][:50], {'needles': scan['machine']})
        helper = self._stage_helper(record, commands, resources) if self.has_helper() else None
        signed = None
        if self.identity is not None:  # the stage equals the flattened dist (checked above); now sign its Mach-Os
            os.mkdir(C / 'signing', 0o700)
            signed = self._sign_backend(record, commands, resources / 'backend')
            unsigned, tree = tree, tree_manifest(resources, 'stage_unsafe')
            changes, _ = tree_differences(unsigned, tree)
            expected = {entry['path'] for entry in signed['files']}
            if {item['path'] for item in changes} != expected or {item['problem'] for item in changes} != {'content_differs'}:
                raise Refused('signing_changed_unexpected_paths', sorted({item['path'] for item in changes} ^ expected),
                              {'differences': changes[:200]})
        # files and links are exactly the walker's, so release_readiness.read_manifest accepts this file (T5 reads it).
        manifest = {
            'schema': 'pebble.candidate-stage/1', 'resources': self.display(resources),
            'algorithm': 'bundle_sha256 = release_readiness.bundle_digest(files); files and links are bundle_entries output',
            'bundle_sha256': tree['bundle_sha256'], 'file_count': tree['file_count'], 'bytes': tree['bytes'],
            'files': tree['files'], 'links': tree['links'], 'modes': tree['modes'],
            'sources': {item['path']: origin(item['path']) for item in tree['files'] + tree['links']},
            'tokenizer': {'path': 'tokenizer/' + TOKENIZER_FILE, 'sha256': TOKENIZER_SHA256,
                          'checked_against': 'backend/pebble/token_budget.py TOKENIZER_SHA256'},
            'backend': {'executable_sha256': backend['executable_sha256'],
                        'candidate_bundle_sha256': backend['candidate_bundle_sha256'],
                        'flattened_bundle_sha256': backend['flattened_bundle_sha256']},
            # Each symlink ditto copied from the dist and flattening replaced; target is what it named.
            'flattened_links': [dict(link, path='backend/' + link['path'], target='backend/' + link['target'])
                                for link in flattened],
            'llama': {'from': self.display(self.llama_from), 'skipped': skipped}}
        if signed is not None:
            # What ships: the signed backend. flattened_bundle_sha256 above stays the unsigned dist's flattened view.
            shipped = bundle_digest(subtree(tree, 'backend')['files'])
            manifest['backend'].update(signed_executable_sha256=signed['executable']['sha256'],
                                       signed_bundle_sha256=shipped)
            manifest['signing'] = signed
        if helper is not None:
            manifest['vault_helper'] = helper
        manifest['machine_paths'] = {'files_scanned': scan['files'], 'machine_specific': 0,
                                     'users_prefix': scan['users_prefix']}
        evidence = {'bundle_sha256': tree['bundle_sha256'], 'file_count': tree['file_count'], 'bytes': tree['bytes'],
                    'links': len(tree['links']), 'flattened_links': len(flattened), 'llama_skipped': skipped,
                    'machine_paths': manifest['machine_paths'],
                    'stage_manifest_sha256': write_new(C / 'stage/stage-manifest.json', manifest)}
        if helper is not None:
            evidence['vault_helper'] = {'sha256': helper['sha256'], 'cdhash': helper['cdhash']}
        if signed is not None:
            evidence.update(signed_files=len(signed['files']), signed_executable_sha256=signed['executable']['sha256'],
                            signed_backend_sha256=shipped, executable_cdhash=signed['executable']['cdhash'])
        if self.copy_mode:
            evidence['shell_source'] = self._shell_source(record, commands, tree)
        return evidence

    def _shell_source(self, record, commands, stage):
        """--shell-from-copy: C/shell-src holds the snapshot's shell inputs, the stage and the frontend output."""
        C, R = self.out, self.root
        shell = C / 'shell-src'
        os.mkdir(shell, 0o700)
        os.mkdir(shell / 'src-tauri', 0o755)
        sources = {}
        for name in sorted(os.listdir(R / 'src-tauri')):
            if name not in SHELL_SKIP:
                copy_entry(R / 'src-tauri' / name, shell / 'src-tauri' / name, sources, 'src-tauri/' + name, links=False)
        for name in SHELL_TOP:
            copy_entry(R / name, shell / name, sources, name, links=False)
        self._run(record, commands['ditto-shell-resources'])
        self._run(record, commands['ditto-shell-dist'])
        files = {rel: file_sha(shell / rel) for rel in sorted(sources) if not os.path.isdir(shell / rel)}
        copied = [self.display(sources[rel]) for rel, digest in files.items() if file_sha(sources[rel]) != digest]
        if copied:
            raise Refused('shell_source_copy_differs', copied)
        stale = [rel for rel, digest in files.items() if rel in self.snapshot and self.snapshot[rel] != digest]
        if stale:
            raise Refused('shell_source_differs_from_snapshot', stale)
        manifest = {'schema': 'pebble.candidate-shell-source/1', 'files': files,
                    'in_snapshot': sorted(rel for rel in files if rel in self.snapshot),
                    'not_in_snapshot': sorted(rel for rel in files if rel not in self.snapshot),
                    'resources_bundle_sha256': stage['bundle_sha256'], 'dist_sha256': self.evidence('frontend')['dist_sha256']}
        digest = write_new(C / 'shell-src-manifest.json', manifest)
        self._shell_source_intact(digest, stage, after_build=False)
        return {'manifest_sha256': digest, 'files': len(files), 'not_in_snapshot': manifest['not_in_snapshot']}

    def _shell_source_intact(self, digest, stage, after_build):
        C = self.out
        shell = C / 'shell-src'
        data = (C / 'shell-src-manifest.json').read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise Refused('shell_source_manifest_changed', [self.display(C / 'shell-src-manifest.json')])
        changed = []
        for rel, expected in json.loads(data)['files'].items():
            try:
                same = file_sha(shell / rel) == expected
            except OSError:
                same = False
            if not same:
                changed.append(self.display(shell / rel))
        if changed:
            raise Refused('shell_source_changed', changed)
        differences, _ = tree_differences(stage, tree_manifest(shell / 'src-tauri/resources', 'shell_source_unsafe'))
        if differences:
            raise Refused('shell_source_resources_differ', [item['path'] for item in differences],
                          {'differences': differences[:200]})
        if tree_manifest(shell / 'dist', 'shell_source_unsafe')['bundle_sha256'] != self.evidence('frontend')['dist_sha256']:
            raise Refused('shell_source_dist_differs', [self.display(shell / 'dist')])
        if after_build:  # build.rs regenerated gen/ in the copy; any byte difference from the checkout's is a finding
            built, shared = {}, {}
            _walk(shell / 'src-tauri', 'gen', built, _content)
            _walk(self.root / 'src-tauri', 'gen', shared, _content)

            def files(found):
                return {path: value.rsplit(':', 1)[1] for path, value in found.items() if value.startswith('file:')}
            built, shared = files(built), files(shared)
            differ = sorted(path for path in built.keys() | shared.keys() if built.get(path) != shared.get(path))
            if differ:
                raise Refused('generated_files_differ', ['src-tauri/' + path for path in differ],
                              "build.rs output in C/shell-src differs from the checkout's src-tauri/gen.")

    def _stage_manifest(self):
        path = self.out / 'stage/stage-manifest.json'
        try:
            data = path.read_bytes()
        except OSError:
            raise Refused('stage_manifest_missing', [self.display(path)]) from None
        if hashlib.sha256(data).hexdigest() != self.evidence('stage')['stage_manifest_sha256']:
            raise Refused('stage_manifest_changed', [self.display(path)])
        return json.loads(data)

    def _stage_tree(self):
        stage = self._stage_manifest()
        return {key: stage[key] for key in ('bundle_sha256', 'files', 'links', 'modes')}

    def _inputs_intact(self, after_build=False):
        """The stage and frontend (and in copy mode the shell source) are exactly what their steps recorded."""
        stage = self._stage_tree()
        differences, _ = tree_differences(stage, tree_manifest(self.out / 'stage/resources', 'stage_changed'))
        if differences:
            raise Refused('stage_changed', [item['path'] for item in differences], {'differences': differences[:200]})
        dist = self.out / 'frontend/dist'
        if tree_manifest(dist, 'frontend_changed')['bundle_sha256'] != self.evidence('frontend')['dist_sha256']:
            raise Refused('frontend_changed', [self.display(dist)])
        if self.copy_mode:
            self._shell_source_intact(self.evidence('stage')['shell_source']['manifest_sha256'], stage, after_build)

