def toolchain_channel(text):
    """The channel of a rust-toolchain.toml, or None."""
    try:
        import tomllib
        channel = (tomllib.loads(text).get('toolchain') or {}).get('channel')
    except ValueError:
        return None
    return channel if isinstance(channel, str) else None


def machine_needles(*paths):
    """The byte strings that would identify this Mac in a shipped binary: each path and the user folder it is in."""
    needles = set()
    for path in paths:
        text = os.path.abspath(str(path))
        needles.add(text)
        parts = Path(text).parts
        if len(parts) >= 3 and parts[1] == 'Users':
            needles.add('/Users/' + parts[2] + '/')
    return sorted(needle.encode() for needle in needles if needle and needle != '/')


def scan_bytes(data, needles, found):
    """Count needles and the generic /Users/ prefix in data."""
    for needle in needles:
        hits = data.count(needle)
        if hits:
            found['machine'][needle.decode('utf-8', 'replace')] = found['machine'].get(needle.decode('utf-8', 'replace'), 0) + hits
    found['users_prefix'] += data.count(b'/Users/')


def machine_path_scan(folder, needles, only=None):
    """V1-023: every regular file below folder (or the relative paths in only), and each member of a .zip there
    (base_library.zip), scanned for this Mac's paths. Returns {files, machine: {needle: hits}, users_prefix,
    paths: [files with a machine hit]}. Content-free: needles are this build's own paths, never file text."""
    found, paths, files = {'machine': {}, 'users_prefix': 0}, [], 0
    import zipfile
    for directory, folders, names in os.walk(folder):
        folders.sort()
        for name in sorted(names):
            path = Path(directory, name)
            rel = path.relative_to(folder).as_posix()
            if (only is not None and rel not in only) or path.is_symlink() or not path.is_file():
                continue
            files += 1
            before = sum(found['machine'].values())
            with open(path, 'rb') as stream:
                data = stream.read(MACHINE_SCAN_BYTES)
            scan_bytes(data, needles, found)
            if name.endswith('.zip'):
                try:
                    with zipfile.ZipFile(path) as archive:
                        for info in archive.infolist()[:20000]:
                            if info.file_size <= 64 << 20:
                                scan_bytes(archive.read(info), needles, found)
                except (zipfile.BadZipFile, OSError, RuntimeError):
                    pass
            if sum(found['machine'].values()) != before:
                paths.append(rel)
    return dict(found, files=files, paths=paths)


def is_macho(head):
    """A Mach-O or fat Mach-O header (a fat header's architecture count is small; a Java class's version is not)."""
    if head[:4] in MACHO[:4]:
        return True
    return head[:4] in (b'\xca\xfe\xba\xbe', b'\xca\xfe\xba\xbf') and int.from_bytes(head[4:8], 'big') < 45


def backend_identifier(rel):
    """The stable code identifier of one staged backend binary: the executable's own, or one from its path."""
    base = signing.IDENTIFIERS['backend']
    if rel == 'pebble-backend':
        return base
    name = re.sub(r'[^A-Za-z0-9._-]+', '-', rel.replace('/', '.')).strip('.-')
    identifier = base + '.' + name
    return identifier if len(identifier) <= 200 else identifier[:180] + '-' + hashlib.sha256(rel.encode()).hexdigest()[:16]


class Refused(Exception):
    """A refusal: a stable code and the exact paths that caused it."""

    def __init__(self, code, paths=(), detail=None):
        super().__init__(code)
        self.code, self.paths, self.detail = code, [str(path) for path in paths], detail

    def report(self):
        return {'refused': self.code, 'paths': self.paths, 'detail': self.detail}


