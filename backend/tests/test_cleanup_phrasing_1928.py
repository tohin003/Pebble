"""Phase 46 (1.9.28, private d-sa-91 k3; b-new): requirements.CLEANUP read "Could you clear out whatever is generated and
can be rebuilt" as no cleanup at all, so that phrasing got no check of what it left. Measured on every visible dev and
private prompt, alternate and follow-up and the false-completions battery (404 texts): the widening adds exactly this
one; the other ten that matched still match the same way.

Restated for w12-bnew's security review (w12b): the widening matched "all compiled ..." or "everything ... generated"
anywhere after a verb, so 9 of the review's 11 ordinary requests ("Remove the debug prints from all compiled
templates") became cleanups and the gate asked to delete build/ and the caches. 1.9.27's own branches did the same with
a preposition before the output ("Remove the debug prints from all generated files") and with a negated verb ("don't
delete the build output"). Now the output must be what the verb deletes. Measured again on the 356 distinct visible
texts (dev and private prompts, alternates, follow-ups, the battery): it fires on the same ten as before (1.9.27's nine
and d-sa-91 k3), on none of the review's eleven, and on no ordinary request below.
"""
import time

import pytest

from pebble import requirements


@pytest.mark.parametrize('text', [
    "This folder is taking too much space. Could you clear out whatever is generated and can be rebuilt (and nothing "
    "else) and tell me what you deleted?",
    "Please delete everything that's generated by the build.",
    'Remove whatever can be regenerated, nothing else.',
    'Clean up all compiled stuff in this repo.',
    'Delete the generated files that can be rebuilt, and nothing else.',  # d-sa-01 k1, as before
    # w12b: the shapes 1.9.27 matched, and a cleanup that names a folder before what it deletes
    'Free up space here: delete only the generated, rebuildable files; list what you removed.',
    'Remove the untracked, rebuildable build output here; nothing else.',
    'Could you get rid of the untracked build output in this repo?',
    'git clean the ignored build output in build/ only.',
    'Delete all of the generated files.',
    "Delete everything in this repo that's generated.",
    "Don't push anything, but delete the build output.",
])
def test_cleanup_requests_are_checked(text):
    assert [r['kind'] for r in requirements.extract(text)] == ['generated_removed']


@pytest.mark.parametrize('text', [
    'Explain what is generated by tools/build.py.',
    'Fix the parser; everything is generated from the grammar anyway, so edit grammar.y.',
    'Remove the duplicate rows from report.csv.',
    'What can be rebuilt here, and how long does a build take?',
    # w12b: the security review's eleven ordinary requests
    'Remove the -O2 flag from all compiled targets in the Makefile.',
    'Delete the unused imports from everything that is generated by protoc, then run the tests.',
    'Remove the debug prints from all compiled templates.',
    "Clean up the formatting of everything that's generated by the codegen script.",
    'Remove the warning that shows whenever anything is compiled.',
    'Delete the line in the Makefile that echoes whatever gets compiled.',
    'Remove the TODO comments in all compiled regexes in parser.py.',
    'Clear the cache in app.py whenever anything is generated.',
    'Remove the old banner from what can be rebuilt by the docs script, i.e. docs/conf.py.',
    'Fix the bug where deleting a user leaves all generated invoices orphaned.',
    "Clean up the code that handles everything that's compiled at startup.",
    # w12b: what 1.9.27 itself read as a cleanup: a preposition or relative word before the output, a negated verb
    'Remove the debug prints from all generated files.',
    'Remove the timestamp from the build output so builds are reproducible.',
    'Remove the code that writes build artifacts to /tmp.',
    "Fix the build script; don't delete the build output.",
    'Never delete the build artifacts in dist/.',
    "Delete the unused imports, and everything that's generated by protoc should be left alone.",
])
def test_other_requests_are_not(text):
    assert 'generated_removed' not in [r['kind'] for r in requirements.extract(text)]


def test_an_edit_of_compiled_templates_never_asks_to_delete_build_output(tmp_path):
    """w12b (the review's probe): an ignored build/ and a cache stay out of an edit request's completion check."""
    (tmp_path / '.gitignore').write_text('build/\n')
    for rel in ('build/app.bin', 'pkg/__pycache__/m.cpython-312.pyc', 'templates/a.html'):
        (tmp_path / rel).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / rel).write_text('x')
    edit = {'payload': {'path': 'templates/a.html'}, 'status': 'applied', 'kind': 'edit', 'created': 1.0}

    def gate(text):
        reqs = requirements.extract(text)
        return requirements.issues(reqs, requirements.baseline(tmp_path, reqs), root=tmp_path, actions=[edit],
                                   answer='Done.', reads=[], test_evidence=[], goal=text)
    assert gate('Remove the debug prints from all compiled templates.') == []
    assert 'build/app.bin' in gate('Delete the generated files that can be rebuilt.')[0][0]


def test_a_cleanup_check_cannot_be_held_up_by_its_own_request():
    """w12b: 20,000 characters (extract's bound) of repeated verbs and objects stay linear."""
    for text in ('delete all of ' * 1500, 'delete everything in ' + 'a/' * 10_000, 'clear out all that ' * 1000,
                 'remove the ' + 'x ' * 10_000):
        start = time.perf_counter()
        requirements.extract(text)
        assert time.perf_counter() - start < 1.0
